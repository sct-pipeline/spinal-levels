"""
This script compares the spinal cord length (PMJ to conus, from 02_compute_cord_length.py) with the body height and
with the lumbosacral spinal level lengths (L1-S2 and L1-L5), and summarizes the cord length by sex. The figure shows
the cord length vs body height (Balgrist localizer and whole-spine datasets pooled), vs cervical length (whole-spine
dataset) and vs lumbar length (Balgrist localizer dataset).

Input:
    - cord_length.csv generated by 02_compute_cord_length.py
    - Excel file with the 'Spinal level heights (mm)' sheet (columns 'Participants' and 'L1' to 'S2', in mm) and the
      'Demographics' sheet (columns 'Participant', 'Sex', 'Weight (kg)' and 'Height (cm)')
    - pmj_to_conus_and_cervical_distance_whole-spine.csv with the PMJ to conus distance and the cervical length of the
      whole-spine dataset (semicolon-separated; columns 'participant_id', 'distance_pmj_to_seg_last_mm',
      'total_C2_C8_distance_mm', 'sex' and 'height_cm')

Output:
    - cord_length_vs_spinal_levels.csv (saved to the same folder as the input CSV): cord length, L1-S2 and L1-L5
      lengths, body height, weight, sex and BMI per subject
    - cord_length_comparison.png (saved to the -o folder): cord length vs body height, C2-C8 length and L1-L5 length,
      with the Spearman correlation and a linear fit with its 95% confidence band

Example:
    python 03_correlation_cord_length.py -i cord_length.csv -xlsx spinal_level_heights_top_L1-bottom_S2.xlsx \
        -whole-spine pmj_to_conus_and_cervical_distance_whole-spine.csv -o figures_across_datasets

Authors: Elia Rochiccioli, Jan Valosek
"""

import os
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import Patch
from scipy import stats

LEVELS = ['L1', 'L2', 'L3', 'L4', 'L5', 'S1', 'S2']
FONT_SIZE = 14

# Female and male colors (same as in ../06_correlation_lumbar_length_height.py); markers distinguish the datasets
SEX_STYLE = {'f': {'color': '#2a78d6', 'label': 'Female'},
             'm': {'color': '#eb6834', 'label': 'Male'}}
DATASET_STYLE = {'localizer': {'marker': 'o', 'size': 50, 'label': 'Balgrist localizer'},
                 'whole-spine': {'marker': '^', 'size': 70, 'label': 'Whole-spine'}}

# Figure panels: (datasets, column, x-axis label, divisor to convert the column to the plotted unit)
PANELS = [(['localizer', 'whole-spine'], 'body_height_cm', 'Height [cm]', 1),
          (['whole-spine'], 'cervical_length_mm', 'Cervical length (C2 to C8) [cm]', 10),
          (['localizer'], 'L1_L5_span_mm', 'Lumbar length (L1 to L5) [cm]', 10)]

def load_excel(fname):
    """
    Load the L1-S2 and L1-L5 lengths and the demographics from the Excel file.
    :param fname: path to the Excel file
    :return: DataFrame with one row per subject
    """
    # Spinal level heights; the total length is the sum of the level heights (only subjects with all levels)
    levels = pd.read_excel(fname, sheet_name='Spinal level heights (mm)')
    levels = levels[levels['Participants'].astype(str).str.startswith('sub-')]
    levels[LEVELS] = levels[LEVELS].apply(pd.to_numeric, errors='coerce')
    levels = levels.dropna(subset=LEVELS)
    spans = pd.DataFrame({'participant_id': levels['Participants'],
                          'L1_S2_span_mm': levels[LEVELS].sum(axis=1).round(1),
                          'L1_L5_span_mm': levels[LEVELS[:5]].sum(axis=1).round(1)})

    demographics = pd.read_excel(fname, sheet_name='Demographics')
    demographics = pd.DataFrame({'participant_id': demographics['Participant'],
                                 'body_height_cm': pd.to_numeric(demographics['Height (cm)'], errors='coerce'),
                                 'weight_kg': pd.to_numeric(demographics['Weight (kg)'], errors='coerce'),
                                 'sex': demographics['Sex'].str.strip().str.lower()})
    demographics['bmi'] = (demographics['weight_kg'] / (demographics['body_height_cm'] / 100) ** 2).round(1)

    return demographics.merge(spans, on='participant_id', how='left')


def spearman_ci(rho, n, alpha=0.05):
    """
    Confidence interval of the Spearman correlation coefficient using the Fisher z-transformation with the
    Bonett & Wright (2000) standard error, sqrt(1.06 / (n - 3)).
    """
    z = np.arctanh(rho)
    se = np.sqrt(1.06 / (n - 3))
    z_crit = stats.norm.ppf(1 - alpha / 2)
    return np.tanh(z - z_crit * se), np.tanh(z + z_crit * se)


def linear_fit_ci_band(x, y, x_fit, alpha=0.05):
    """
    Linear fit and the confidence band of the fitted mean (ordinary least squares).
    :return: y_fit, lower bound, upper bound evaluated at x_fit
    """
    n = len(x)
    slope, intercept = np.polyfit(x, y, 1)
    y_fit = slope * x_fit + intercept
    residuals = y - (slope * x + intercept)
    s = np.sqrt(np.sum(residuals ** 2) / (n - 2))   # residual standard error
    se_fit = s * np.sqrt(1 / n + (x_fit - x.mean()) ** 2 / np.sum((x - x.mean()) ** 2))
    t_crit = stats.t.ppf(1 - alpha / 2, n - 2)
    return y_fit, y_fit - t_crit * se_fit, y_fit + t_crit * se_fit


def format_p(p):
    """
    Format the p-value for the figure, e.g. 'p = 0.011' or 'p < 0.001'.
    """
    return 'p < 0.001' if p < 0.001 else f'p = {p:.3f}'


def format_axis(ax, xlabel):
    """
    Axis labels, grid and spines shared by all panels.
    """
    ax.set_xlabel(xlabel, fontsize=FONT_SIZE)
    ax.set_ylabel('Cord length PMJ to conus [mm]', fontsize=FONT_SIZE)
    ax.tick_params(axis='both', labelsize=FONT_SIZE - 2)
    ax.grid(alpha=0.2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)


def main():
    parser = argparse.ArgumentParser(description='Compare the spinal cord length with body height and lumbosacral '
                                                 'spinal level lengths.')
    parser.add_argument('-i', required=True, help='cord_length.csv generated by 02_compute_cord_length.py')
    parser.add_argument('-xlsx', required=True,
                        help='Excel file with the "Spinal level heights (mm)" and "Demographics" sheets')
    parser.add_argument('-whole-spine', required=True,
                        help='pmj_to_conus_and_cervical_distance_whole-spine.csv with the PMJ to conus distance and '
                             'the cervical length of the whole-spine dataset')
    parser.add_argument('-o', help='Output folder for the figure. Default: the folder of the input CSV')
    args = parser.parse_args()
    path_out = os.path.dirname(os.path.abspath(args.i))

    df = pd.read_csv(args.i).rename(columns={'cord_length_along_centerline_mm': 'cord_length_mm'})
    df = df[['participant_id', 'cord_length_mm']]
    df = df.merge(load_excel(args.xlsx), on='participant_id', how='left').sort_values('participant_id')
    df = df[['participant_id', 'cord_length_mm', 'L1_S2_span_mm', 'L1_L5_span_mm', 'body_height_cm', 'weight_kg',
             'sex', 'bmi']]
    fname_csv = os.path.join(path_out, 'cord_length_vs_spinal_levels.csv')
    df.to_csv(fname_csv, index=False)
    print(f'Saved {fname_csv}')

    # Summary (mean ± SD)
    cord = df['cord_length_mm']
    print(f'\nCord length: {cord.mean():.1f} ± {cord.std():.1f} mm (range {cord.min():.0f}-{cord.max():.0f}, '
          f'n={len(cord)})')
    for sex, group in df.groupby('sex'):
        print(f'  {sex}: {group["cord_length_mm"].mean():.1f} ± {group["cord_length_mm"].std():.1f} mm '
              f'(n={len(group)})')

    # Whole-spine dataset, renamed to the localizer column names; the separator (';' or ',') is detected automatically
    df_whole_spine = pd.read_csv(args.whole_spine, sep=None, engine='python')
    df_whole_spine = df_whole_spine.rename(columns={'distance_pmj_to_seg_last_mm': 'cord_length_mm',
                                                    'total_C2_C8_distance_mm': 'cervical_length_mm',
                                                    'height_cm': 'body_height_cm'})
    df_whole_spine['sex'] = df_whole_spine['sex'].str.strip().str.lower()   # 'F'/'M' -> 'f'/'m'
    df_all = pd.concat([df.assign(dataset='localizer'), df_whole_spine.assign(dataset='whole-spine')],
                       ignore_index=True)

    # Correlations and figure: cord length vs body height, cervical length and lumbar length
    fig, axes = plt.subplots(1, 3, figsize=(16, 5.3))
    for ax, letter, (datasets, col, xlabel, scale) in zip(axes, 'ABC', PANELS):
        # Panel letter in the upper left corner, outside the axes
        ax.text(-0.15, 1.1, letter, transform=ax.transAxes, fontsize=FONT_SIZE + 4, fontweight='bold',
                va='bottom', ha='left')
        data = df_all[df_all['dataset'].isin(datasets)].dropna(subset=[col, 'cord_length_mm'])
        x, y = data[col].astype(float) / scale, data['cord_length_mm'].astype(float)
        rho, p = stats.spearmanr(x, y)
        rho_lo, rho_hi = spearman_ci(rho, len(data))
        print(f'{"+".join(datasets)}: cord length vs {col}: Spearman rho={rho:+.2f} [95% CI {rho_lo:+.2f}, '
              f'{rho_hi:+.2f}], p={p:.3f}, n={len(data)}')

        # Linear fit across all subjects (only as a visual guide) with its 95% confidence band
        x_fit = np.linspace(x.min(), x.max(), 100)
        y_fit, y_lo, y_hi = linear_fit_ci_band(x.to_numpy(), y.to_numpy(), x_fit)
        ax.fill_between(x_fit, y_lo, y_hi, color='gray', alpha=0.2, linewidth=0, zorder=1)
        ax.plot(x_fit, y_fit, color='black', linewidth=2, zorder=2)
        # Scatter plot, colored by sex, marker by dataset
        for dataset in datasets:
            for sex, style in SEX_STYLE.items():
                mask = (data['dataset'] == dataset) & (data['sex'] == sex)
                ax.scatter(x[mask], y[mask], color=style['color'], marker=DATASET_STYLE[dataset]['marker'],
                           s=DATASET_STYLE[dataset]['size'],
                           edgecolor='white', zorder=3)

        n_f, n_m = (data['sex'] == 'f').sum(), (data['sex'] == 'm').sum()
        ax.set_title(f'Spearman ρ = {rho:+.2f} [95% CI {rho_lo:+.2f}, {rho_hi:+.2f}], {format_p(p)}\n'
                     f'n = {len(data)} (F {n_f}, M {n_m})', fontsize=FONT_SIZE - 3)
        format_axis(ax, xlabel)

    # Shared legend below the panels
    # Sex by color, dataset by (gray) marker, with the number of participants across the figure
    handles = [Line2D([], [], color=style['color'], marker='o', linestyle='', markersize=8)
               for style in SEX_STYLE.values()] + \
              [Line2D([], [], color='gray', marker=style['marker'], linestyle='', markersize=8)
               for style in DATASET_STYLE.values()] + \
              [Patch(color='gray', alpha=0.2, linewidth=0)]
    labels = [f"{style['label']} (n = {(df_all['sex'] == sex).sum()})" for sex, style in SEX_STYLE.items()] + \
             [f"{style['label']} (n = {(df_all['dataset'] == dataset).sum()})"
              for dataset, style in DATASET_STYLE.items()] + \
             ['Linear fit, 95% CI']
    fig.legend(handles, labels, loc='lower center', ncol=5, frameon=False, fontsize=FONT_SIZE - 2,
               bbox_to_anchor=(0.5, -0.02), handletextpad=0.3, columnspacing=1.5)
    plt.tight_layout(rect=(0, 0.06, 1, 1), w_pad=3)
    path_fig = os.path.abspath(args.o) if args.o else path_out
    os.makedirs(path_fig, exist_ok=True)
    fname_png = os.path.join(path_fig, 'cord_length_comparison.png')
    plt.savefig(fname_png, dpi=300)
    print(f'Saved {fname_png}')


if __name__ == '__main__':
    main()
