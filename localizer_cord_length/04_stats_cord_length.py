"""
This script computes the statistics of the spinal cord length (PMJ to conus):
    - descriptive statistics
    - female vs male comparison
    - correlation with body height, for the Balgrist localizer dataset, the whole-spine dataset and both datasets pooled.
    - for the pooled data, it also fits linear models to test whether the sex difference remains after adjusting for the dataset and body height.

Tests:
    - Female vs male: Welch t-test (main; unequal group sizes, does not assume equal variances), with the Shapiro-Wilk
      normality test per group, Mann-Whitney U test and Student t-test for reference
    - Correlation with body height: Spearman (main, with 95% CI) and Pearson
    - Pooled data: OLS models 'cord_length ~ sex + dataset' and 'cord_length ~ sex + dataset + height'

Input:
    - cord_length_vs_spinal_levels.csv generated by 03_correlation_cord_length.py (Balgrist localizer dataset)
    - pmj_to_conus_and_cervical_distance_whole-spine.csv with the PMJ to conus distance of the whole-spine dataset
      (semicolon-separated; columns 'participant_id', 'distance_pmj_to_seg_last_mm', 'sex' and 'height_cm')

Output (saved to the -o folder):
    - cord_length_stats.csv: one row per dataset (Balgrist localizer, whole-spine, pooled) with the statistics
    - the statistics and the linear models are also printed to the terminal

Example:
    python 04_stats_cord_length.py -localizer cord_length_vs_spinal_levels.csv \
        -whole-spine pmj_to_conus_and_cervical_distance_whole-spine.csv -o figures_across_datasets

Author: Jan Valosek
"""

import os
import argparse
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf
from scipy import stats


def spearman_ci(rho, n, alpha=0.05):
    """
    Confidence interval of the Spearman correlation coefficient using the Fisher z-transformation with the
    Bonett & Wright (2000) standard error, sqrt(1.06 / (n - 3)).
    """
    z = np.arctanh(rho)
    se = np.sqrt(1.06 / (n - 3))
    z_crit = stats.norm.ppf(1 - alpha / 2)
    return np.tanh(z - z_crit * se), np.tanh(z + z_crit * se)


def load_data(fname_localizer, fname_whole_spine):
    """
    Load both datasets into one DataFrame with the columns participant_id, dataset, sex ('f'/'m'), height_cm and
    cord_length_cm.
    """
    df_loc = pd.read_csv(fname_localizer)
    df_loc = pd.DataFrame({'participant_id': df_loc['participant_id'],
                           'dataset': 'Balgrist localizer',
                           'sex': df_loc['sex'],
                           'height_cm': df_loc['body_height_cm'],
                           'cord_length_cm': df_loc['cord_length_mm'] / 10})
    # The separator (';' or ',') is detected automatically
    df_ws = pd.read_csv(fname_whole_spine, sep=None, engine='python')
    df_ws = pd.DataFrame({'participant_id': df_ws['participant_id'],
                          'dataset': 'Whole-spine',
                          'sex': df_ws['sex'],
                          'height_cm': df_ws['height_cm'],
                          'cord_length_cm': df_ws['distance_pmj_to_seg_last_mm'] / 10})
    df = pd.concat([df_loc, df_ws], ignore_index=True)
    df['sex'] = df['sex'].str.strip().str.lower()   # 'F'/'M' -> 'f'/'m'
    return df.dropna(subset=['sex', 'height_cm', 'cord_length_cm'])


def compute_stats(df, name):
    """
    Descriptive statistics, female vs male comparison and correlation with body height for one group of subjects.
    :return: dict with the statistics
    """
    y = df['cord_length_cm']
    f, m = y[df['sex'] == 'f'], y[df['sex'] == 'm']
    rho, p_rho = stats.spearmanr(df['height_cm'], y)
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    r, p_r = stats.pearsonr(df['height_cm'], y)
    return {'dataset': name, 'n': len(df), 'n_f': len(f), 'n_m': len(m),
            'mean_cm': y.mean(), 'sd_cm': y.std(), 'min_cm': y.min(), 'max_cm': y.max(),
            'mean_f_cm': f.mean(), 'sd_f_cm': f.std(), 'mean_m_cm': m.mean(), 'sd_m_cm': m.std(),
            'shapiro_p_f': stats.shapiro(f).pvalue, 'shapiro_p_m': stats.shapiro(m).pvalue,
            'welch_t_p': stats.ttest_ind(f, m, equal_var=False).pvalue,
            'mann_whitney_p': stats.mannwhitneyu(f, m).pvalue,
            'student_t_p': stats.ttest_ind(f, m).pvalue,
            'spearman_rho_height': rho, 'spearman_ci_lo': rho_lo, 'spearman_ci_hi': rho_hi,
            'spearman_p_height': p_rho, 'pearson_r_height': r, 'pearson_p_height': p_r}


def print_stats(s):
    """
    Print the statistics of one group of subjects in the format used in the Results.
    """
    print(f"\n=== {s['dataset']}: n = {s['n']} (F {s['n_f']}, M {s['n_m']}) ===")
    print(f"Cord length: {s['mean_cm']:.2f} ± {s['sd_cm']:.2f} cm (range {s['min_cm']:.2f}–{s['max_cm']:.2f} cm)")
    print(f"Females vs males: {s['mean_f_cm']:.2f} ± {s['sd_f_cm']:.2f} vs. {s['mean_m_cm']:.2f} ± "
          f"{s['sd_m_cm']:.2f} cm")
    print(f"  Shapiro-Wilk p: F = {s['shapiro_p_f']:.3f}, M = {s['shapiro_p_m']:.3f}")
    print(f"  Welch t-test p = {s['welch_t_p']:.3f} (Mann-Whitney U p = {s['mann_whitney_p']:.3f}, "
          f"Student t-test p = {s['student_t_p']:.3f})")
    print(f"Correlation with height: Spearman ρ = {s['spearman_rho_height']:+.2f} [95% CI {s['spearman_ci_lo']:+.2f}, "
          f"{s['spearman_ci_hi']:+.2f}], p = {s['spearman_p_height']:.3g}; Pearson r = {s['pearson_r_height']:+.2f}, "
          f"p = {s['pearson_p_height']:.3g}")


def main():
    parser = argparse.ArgumentParser(description='Compute the cord length statistics (sex difference and correlation '
                                                 'with height) for the Balgrist localizer and whole-spine datasets.')
    parser.add_argument('-localizer', required=True,
                        help='cord_length_vs_spinal_levels.csv generated by 03_correlation_cord_length.py')
    parser.add_argument('-whole-spine', required=True,
                        help='pmj_to_conus_and_cervical_distance_whole-spine.csv with the PMJ to conus distance of the '
                             'whole-spine dataset')
    parser.add_argument('-o', help='Output folder. Default: the folder of the -localizer CSV')
    args = parser.parse_args()

    df = load_data(args.localizer, args.whole_spine)

    # Per dataset and pooled
    results = [compute_stats(group, name) for name, group in df.groupby('dataset')]
    results.append(compute_stats(df, 'Pooled'))
    for s in results:
        print_stats(s)

    # Pooled: is the sex difference explained by the dataset and body height?
    print('\n=== Pooled: linear models (reference: female, Balgrist localizer) ===')
    print(pd.crosstab(df['dataset'], df['sex']))
    for formula in ['cord_length_cm ~ sex + dataset', 'cord_length_cm ~ sex + dataset + height_cm']:
        model = smf.ols(formula, data=df).fit()
        ci = model.conf_int()
        print(f'\n{formula} (R² = {model.rsquared:.2f})')
        for term in model.params.index.drop('Intercept'):
            print(f'  {term}: β = {model.params[term]:+.3f} [95% CI {ci.loc[term, 0]:+.3f}, {ci.loc[term, 1]:+.3f}], '
                  f'p = {model.pvalues[term]:.3g}')

    path_out = os.path.abspath(args.o) if args.o else os.path.dirname(os.path.abspath(args.localizer))
    os.makedirs(path_out, exist_ok=True)
    fname_csv = os.path.join(path_out, 'cord_length_stats.csv')
    pd.DataFrame(results).round(4).to_csv(fname_csv, index=False)
    print(f'\nSaved {fname_csv}')


if __name__ == '__main__':
    main()
