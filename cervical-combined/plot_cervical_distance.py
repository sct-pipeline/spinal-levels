"""
This script plots the distance between the C2 and C8 spinal levels for each subject, from one or more CSV tables
generated by `compute_cervical_distance.py` (one table per dataset, files `spinal_levels_*_distance_2-8_*_<dataset>.csv`).

Several tables can be passed to `-i` (e.g. tables generated in separate runs for different datasets, or a
rootlets-based table and a centerline/final-table-based one); they are concatenated and plotted in one figure.
All tables must contain the same distance type (midpoint or total), unless `-distance` is given explicitly.
Rows present in more than one table (same dataset/subject/session) are kept only once (first table wins).

Tables with a "session" column keep only the rows of `-session` (default ses-A; "all" keeps every session); tables
without session values are kept as they are.

The column separator (',', ';' or tab) is detected per file, so tables with different separators can be mixed.
Final tables (subject, session, slice_top_C2_I-S, slice_bottom_C8_I-S, length_C2-C8_centerline_mm, sex, age,
dataset) can also be passed directly: `length_C2-C8_centerline_mm` is used as the total C2-C8 distance. Tables without
a height column are plotted with unknown height (use `-sort-by length` to order them), tables without a dataset column
get the file name as dataset.

Figure layout:
- color = sex (red = female, blue = male, gray = unknown); markers have a white border (`-marker-edge-width`)
- marker = dataset, fixed per dataset name in visualisation_utils.py (Dataset 1 = circle, Dataset 2 = square,
  Dataset 3 = asterisk, Dataset 4 = triangle), consistent across scripts even if only some datasets are included
- x-axis: all subjects (females and males together) sorted by height (`-sort-by height`, default) or by the plotted
  C2-C8 length (`-sort-by length`). With `-stratify-by-sex`, females come first, then males, each group sorted
  separately and separated by a dashed line. When sorted by height, subjects without height are placed at the end
  (no separator line); use `-exclude-missing-height` to leave them out of the figure
- one point per row of the tables, i.e. per subject/session for final tables with several sessions

Example:
    python plot_cervical_distance.py \
        -i figures-and-dataframes/spinal_levels_total_distance_2-8_ref_c2_method_rootlets_data-multi-subject.csv \
           figures-and-dataframes/spinal_levels_total_distance_2-8_method_centerline_uk.csv \
        -sort-by length

Output:
- Figure with the distance for each subject (all datasets of all tables in one figure), saved next to the first CSV
  table by default. The default file name contains the distance, the method(s), the plotted datasets and the sort
  order, e.g. figure_spinal_levels_total_distance_2-8_method_rootlets+centerline_datasets_ds1+uk_sorted_by_height.png
  (or ..._sorted_by_cervical_length.png with `-sort-by length`, plus _stratified_by_sex with `-stratify-by-sex`)
"""

import os
import argparse

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.markers import MarkerStyle
# Shared plotting conditions (font, sex colors, dataset markers, marker sizes, legend), same in all figure scripts
from visualisation_utils import (SPINAL_REGIONAL_LENGTH_FIGSIZE, FONT_SIZE, SEX_ORDER, SEX_LABEL, SEX_COLOR,
                                 get_dataset_markers, scatter_points, legend_handles, add_legend_above)
# Column names and levels shared with the table script
from compute_cervical_distance import FIRST_LEVEL, LAST_LEVEL, DISTANCE_COL, HEIGHT_COL


# Columns every input table must contain
REQUIRED_COLUMNS = ['subject', 'sex']
# Centerline length column of the final tables (subject;session;...;length_C2-C8_centerline_mm;sex;age;dataset),
# used as the total C2-C8 distance when the table has no total_distance_mm column
FINAL_TABLE_LENGTH_COL = 'length_C2-C8_centerline_mm'
# Candidate column separators, detected per file from its header line
SEPARATORS = [',', ';', '\t']


def detect_separator(fname):
    """
    Detect the column separator of a CSV/TSV file (',', ';' or tab) from its header line: the candidate that occurs
    most often wins (',' if none occurs).
    """
    with open(fname, encoding='utf-8-sig') as f:
        header = f.readline()
    counts = {sep: header.count(sep) for sep in SEPARATORS}
    sep = max(counts, key=counts.get)
    return sep if counts[sep] > 0 else ','


def read_table(fname):
    """
    Read a CSV/TSV file with an auto-detected separator, with stripped column names.
    """
    df = pd.read_csv(fname, sep=detect_separator(fname), encoding='utf-8-sig')
    df.columns = df.columns.str.strip()
    return df


def harmonize_table(df, fname):
    """
    Bring a table to the columns used for plotting: final tables get total_distance_mm from the centerline length,
    a missing dataset column is filled with the file name, a missing height column with NaN, and sex is normalized
    to 'F' / 'M' (anything else becomes NaN).
    :param df: dataframe read from `fname`
    :param fname: path of the table (used for the default dataset name and messages)
    :return: harmonized dataframe
    """
    total_col = DISTANCE_COL['total']
    if total_col not in df.columns and FINAL_TABLE_LENGTH_COL in df.columns:
        df[total_col] = pd.to_numeric(df[FINAL_TABLE_LENGTH_COL], errors='coerce')
        df['distance_type'] = 'total'
        if 'method' not in df.columns:
            df['method'] = 'centerline'
        print(f'INFO: {os.path.basename(fname)}: {FINAL_TABLE_LENGTH_COL} used as the total C2-C8 distance.')
    if 'dataset' not in df.columns:
        df['dataset'] = os.path.splitext(os.path.basename(fname))[0]
        print(f'WARNING: no "dataset" column in {fname}; using "{df["dataset"].iloc[0]}".')
    if HEIGHT_COL not in df.columns:
        df[HEIGHT_COL] = np.nan
        print(f'WARNING: no "{HEIGHT_COL}" column in {os.path.basename(fname)}; height is unknown for its rows '
              f'(consider -sort-by length).')
    sex = df['sex'].astype(str).str.strip().str.upper().str[0]
    df['sex'] = sex.where(sex.isin(['F', 'M']))
    df['subject'] = df['subject'].astype(str).str.strip()
    df['dataset'] = df['dataset'].astype(str).str.strip()
    return df


def get_parser():
    """
    Function to parse command line arguments.
    :return: command line arguments
    """
    parser = argparse.ArgumentParser(description='Plot the distance between the C2 and C8 spinal levels for each '
                                                 'subject from one or more combined CSV tables generated by '
                                                 'compute_cervical_distance.py.',
                                     prog=os.path.basename(__file__).strip('.py'))
    parser.add_argument('-i', required=True, nargs='+', type=str,
                        help='One or more CSV tables generated by compute_cervical_distance.py (one per dataset) or '
                             'final tables. All tables are plotted together in one figure.')
    parser.add_argument('-distance', choices=['auto', 'midpoint', 'total'], default='auto',
                        help='Distance to plot. "auto" uses the distance_type column of the tables. Default: auto')
    parser.add_argument('-session', default='ses-A',
                        help='For tables with a "session" column, keep only the rows of this session; tables without '
                             'session values are kept as they are. Use "all" to keep all sessions. Default: ses-A')
    parser.add_argument('-sort-by', choices=['height', 'length'], default='height',
                        help='Order of the subjects on the x-axis: by height or by the plotted C2-C8 length '
                             '(ascending). Default: height')
    parser.add_argument('-stratify-by-sex', action='store_true',
                        help='Sort females and males in separate groups (females first), separated by a dashed line. '
                             'Default: all subjects sorted together, sex shown by color only.')
    parser.add_argument('-exclude-missing-height', action='store_true',
                        help='Do not plot subjects without height. Default: they are plotted (at the end when sorted '
                             'by height).')
    parser.add_argument('-marker-edge-width', type=float, default=0.8,
                        help='Width (points) of the white border around the markers; 0 disables it. Default: 0.8')
    parser.add_argument('-output-folder', default=None,
                        help='Folder where the figure will be saved. Default: folder of the first input CSV table.')
    parser.add_argument('-figure-name', default=None,
                        help='File name of the figure (e.g. figure_c2_c8.png). Default: built from the distance, '
                             'method(s), plotted datasets and sort order, e.g. figure_spinal_levels_total_distance_2-8'
                             '_method_rootlets_datasets_ds1+ds2_sorted_by_height.png')
    parser.add_argument('-no-show', action='store_true', help='Do not open the figure window.')
    return parser


def filter_session(df, session, fname):
    """
    Keep only the rows of `session` if the table has session values; tables without a session column or with an
    empty one are returned unchanged. `session='all'` keeps all sessions.
    :param df: dataframe of one table
    :param session: session to keep (e.g. 'ses-A') or 'all'
    :param fname: path of the table (used in the messages)
    :return: filtered dataframe
    """
    if session == 'all' or 'session' not in df.columns or df['session'].isna().all():
        return df
    sessions = df['session'].astype(str).str.strip()
    keep = sessions == session
    if not keep.any():
        print(f'WARNING: {os.path.basename(fname)} has no rows of {session} (sessions: '
              f'{sorted(sessions.unique())}); none of its rows are plotted.')
    elif (~keep).any():
        print(f'INFO: {os.path.basename(fname)}: kept {int(keep.sum())} row(s) of {session}, dropped '
              f'{int((~keep).sum())} row(s) of other sessions ({sorted(sessions[~keep].unique())}).')
    return df[keep].reset_index(drop=True)


def load_tables(fnames, parser, session='ses-A'):
    """
    Load and concatenate the input tables. Tables with session values keep only the rows of `session`. A
    'source_table' column records the file each row comes from; rows present in more than one table (same
    dataset/subject/session) are kept only once (first table wins).
    :param fnames: list of paths to the CSV tables
    :param parser: argument parser (for error messages)
    :param session: session to keep (e.g. 'ses-A') or 'all'
    :return: concatenated dataframe
    """
    list_df = []
    for fname in fnames:
        if not os.path.isfile(fname):
            parser.error(f'{fname} does not exist.')
        sep = detect_separator(fname)
        df = read_table(fname)
        missing = [col for col in REQUIRED_COLUMNS if col not in df.columns]
        if missing:
            parser.error(f'{fname} lacks the column(s) {missing} (detected separator {sep!r}); generate it with '
                         f'compute_cervical_distance.py or check the file.')
        if not any(col in df.columns for col in list(DISTANCE_COL.values()) + [FINAL_TABLE_LENGTH_COL]):
            parser.error(f'{fname} has no distance column ({list(DISTANCE_COL.values()) + [FINAL_TABLE_LENGTH_COL]}).')
        df = harmonize_table(df, fname)
        df = filter_session(df, session, fname)
        df['source_table'] = os.path.basename(fname)
        print(f'Loaded {fname} (separator {sep!r}): {len(df)} row(s), '
              f'datasets: {", ".join(map(str, df["dataset"].unique()))}')
        list_df.append(df)
    df_all = pd.concat(list_df, ignore_index=True)

    # Drop rows repeated across tables (same dataset/subject/session)
    if 'session' not in df_all.columns:
        df_all['session'] = np.nan
    key = df_all['dataset'].astype(str) + '/' + df_all['subject'].astype(str) + '/' + \
        df_all['session'].fillna('').astype(str)
    duplicated = key.duplicated(keep='first') & (df_all['source_table'] != df_all.groupby(key)['source_table']
                                                 .transform('first'))
    if duplicated.any():
        print(f'WARNING: {int(duplicated.sum())} row(s) appear in more than one table and are kept only once '
              f'(first table wins): {key[duplicated].unique().tolist()}')
        df_all = df_all[~duplicated].reset_index(drop=True)
    return df_all


def add_marker_edges(ax, n_collections, n_lines, color='white', width=0.8):
    """
    Add an edge (border) around the markers drawn on `ax` since `n_collections` collections and `n_lines` lines
    existed, i.e. the points drawn by one scatter_points() call (visualisation_utils.py), whether it uses ax.scatter
    or ax.plot. Call it right after each scatter_points() call, only for filled markers (see is_filled_marker()).
    :param ax: matplotlib axes
    :param n_collections: number of ax.collections before the points were drawn
    :param n_lines: number of ax.lines before the points were drawn
    :param color: edge color
    :param width: edge width in points
    """
    for collection in list(ax.collections)[n_collections:]:
        collection.set_edgecolor(color)
        collection.set_linewidth(width)
    for line in list(ax.lines)[n_lines:]:
        if line.get_marker() in (None, '', 'None', ' '):
            continue  # line without marker
        line.set_markeredgecolor(color)
        line.set_markeredgewidth(width)


def is_filled_marker(marker):
    """
    True for filled markers ('o', 's', '^', '*', ...). Unfilled markers ('x', '+', '1', ...) are drawn with their edge
    only, so a white edge would hide them.
    """
    try:
        return MarkerStyle(marker).is_filled()
    except (ValueError, TypeError):
        return False


def get_distance(df, distance):
    """
    Return the distance type to plot ('midpoint' or 'total'): `distance` if given, otherwise from the
    'distance_type' column, otherwise from the available distance columns.
    """
    if distance != 'auto':
        return distance
    if 'distance_type' in df.columns:
        types = df['distance_type'].dropna().unique()
        if len(types) == 1:
            return types[0]
        if len(types) > 1:
            raise ValueError(f'The tables contain different distance types {list(types)}; pass -distance to choose '
                             f'one (rows without that distance are not plotted).')
    available = [name for name, col in DISTANCE_COL.items() if col in df.columns]
    if len(available) == 1:
        return available[0]
    raise ValueError(f'Cannot infer the distance from the tables; pass -distance {list(DISTANCE_COL)}.')


def order_subjects(df_subjects, dist_col, sort_by='height', height_col=HEIGHT_COL, stratify_by_sex=False):
    """
    Order subjects on the x-axis, sorted (ascending) by height (subjects without height at the end) or by the plotted
    length. By default all subjects are sorted together (females and males mixed); with `stratify_by_sex`, females
    come first, then males, then subjects with unknown sex, each group sorted separately.
    :param df_subjects: dataframe with one row per subject (or subject/session) and 'sex', 'dataset', 'subject',
    `dist_col` and `height_col` columns
    :param dist_col: name of the column with the plotted distance (mm), used when `sort_by` is 'length'
    :param sort_by: 'height' or 'length'
    :param height_col: name of the column with subject height (cm)
    :param stratify_by_sex: sort females and males in separate groups
    :return: ordered copy with added 'sex_key' and 'x' (1-based x-position) columns
    """
    df = df_subjects.copy()
    df[height_col] = pd.to_numeric(df[height_col], errors='coerce')
    df['sex_key'] = df['sex'].where(df['sex'].isin(['F', 'M']), 'unknown')
    df['sex_rank'] = df['sex_key'].map({sex: i for i, sex in enumerate(SEX_ORDER)})
    df['no_height'] = df[height_col].isna()
    if sort_by == 'length':
        sort_keys = [dist_col, height_col]
    else:
        sort_keys = ['no_height', height_col, dist_col]
    sort_cols = (['sex_rank'] if stratify_by_sex else []) + sort_keys + ['dataset', 'subject'] + \
                (['session'] if 'session' in df.columns else [])
    df = df.sort_values(sort_cols).drop(columns=['sex_rank', 'no_height']).reset_index(drop=True)
    df['x'] = np.arange(1, len(df) + 1)
    return df


def draw_sex_groups(ax, df_ordered):
    """
    Draw a dashed vertical line between the sex groups and label each group above the points (used with
    -stratify-by-sex only).
    :param ax: matplotlib axes
    :param df_ordered: dataframe returned by order_subjects() with stratify_by_sex=True
    """
    first_group = True
    for sex_key in SEX_ORDER:
        df_group = df_ordered[df_ordered['sex_key'] == sex_key]
        if df_group.empty:
            continue
        x_start, x_end = df_group['x'].min(), df_group['x'].max()
        # Dashed line between groups
        if not first_group:
            ax.axvline(x_start - 0.5, color='black', linestyle='--', linewidth=1, alpha=0.7, zorder=2)
        first_group = False
        # Group label centered above the group
        ax.text((x_start + x_end) / 2, 0.98, SEX_LABEL[sex_key], color=SEX_COLOR[sex_key],
                transform=ax.get_xaxis_transform(), ha='center', va='top', fontsize=FONT_SIZE - 3)


def style_axes(ax, n_subjects, distance, first_level, last_level, sort_by='height', stratify_by_sex=False):
    """
    Common axes styling.
    """
    ax.set_xlim(0.5, n_subjects + 0.5)
    sort_label = 'height' if sort_by == 'height' else f'C{first_level}–C{last_level} length'
    stratified = 'stratified by sex and ' if stratify_by_sex else ''
    ax.set_xlabel(f'Subjects {stratified}sorted by {sort_label}', fontsize=FONT_SIZE)
    ax.set_ylim(7, 13)
    if distance == 'total':
        ax.set_ylabel(f'Length top C{first_level} – bottom C{last_level} [cm]', fontsize=FONT_SIZE)
    else:
        ax.set_ylabel(f'Length midpoint C{first_level} – midpoint C{last_level} [cm]', fontsize=FONT_SIZE)
    ax.tick_params(axis='y', labelsize=FONT_SIZE - 2)
    ax.set_xticks([])  # no tick marks or numbers on the x-axis
    ax.grid(axis='y', alpha=0.2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)


def generate_distance_figure(df_distance, fname_figure, distance, first_level=FIRST_LEVEL, last_level=LAST_LEVEL,
                             height_col=HEIGHT_COL, show=True, sort_by='height', marker_edge_width=0.8,
                             stratify_by_sex=False):
    """
    Generate a figure with subjects on the x-axis (all sorted together by height or by length, see `sort_by`; or
    females first, then males, with `stratify_by_sex`) and the distance between the `first_level` and `last_level` on
    the y-axis (one point per row). Color encodes sex, marker encodes dataset (fixed per dataset name, see
    DATASET_MARKERS in visualisation_utils.py).
    :param df_distance: concatenated tables generated by compute_cervical_distance.py
    :param fname_figure: path of the output figure
    :param distance: distance to plot ('midpoint' or 'total')
    :param first_level: first spinal level
    :param last_level: last spinal level
    :param height_col: name of the column with subject height (cm)
    :param show: open the figure window
    :param sort_by: order of the subjects on the x-axis, 'height' or 'length'
    :param marker_edge_width: width of the white border around the markers (points); 0 disables it
    :param stratify_by_sex: sort females and males in separate groups, separated by a dashed line
    """
    dist_col = DISTANCE_COL[distance]
    # Fixed marker per dataset name (independent of which datasets are included and of their order)
    dataset_markers = get_dataset_markers(df_distance['dataset'].unique())
    df_plot = order_subjects(df_distance, dist_col, sort_by, height_col, stratify_by_sex)

    fig, ax = plt.subplots(figsize=SPINAL_REGIONAL_LENGTH_FIGSIZE)
    for dataset, marker in dataset_markers.items():
        for sex_key in SEX_ORDER:
            df_sub = df_plot[(df_plot['dataset'] == dataset) & (df_plot['sex_key'] == sex_key)]
            if df_sub.empty:
                continue
            n_collections, n_lines = len(ax.collections), len(ax.lines)
            scatter_points(ax, df_sub['x'], df_sub[dist_col] / 10,  # convert mm to cm for plotting
                           color=SEX_COLOR[sex_key], marker=marker)
            # White border around filled markers (helps to see overlapping points)
            if marker_edge_width > 0 and is_filled_marker(marker):
                add_marker_edges(ax, n_collections, n_lines, color='white', width=marker_edge_width)

    if stratify_by_sex:
        draw_sex_groups(ax, df_plot)
    style_axes(ax, len(df_plot), distance, first_level, last_level, sort_by, stratify_by_sex)

    # Shared legend above the plot: sex (color) then datasets (marker), with n
    add_legend_above(ax, legend_handles(df_plot, dataset_markers, sex_col='sex_key'))

    plt.tight_layout()
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')
    if show:
        plt.show()
    plt.close(fig)


def safe_name(text):
    """
    Make a string safe for a file name: spaces and path separators become '-'.
    """
    return str(text).strip().replace(' ', '-').replace('/', '-').replace('\\', '-')


def default_figure_name(df, distance, sort_by, stratify_by_sex=False):
    """
    Default figure file name with the distance type, the method(s), the plotted datasets (in the order of the input
    tables) and the sort order, e.g.
    figure_spinal_levels_total_distance_2-8_method_rootlets+centerline_datasets_ds1+uk_sorted_by_cervical_length.png
    :param df: plotted dataframe (after all filters)
    :param distance: plotted distance ('midpoint' or 'total')
    :param sort_by: 'height' or 'length'
    :param stratify_by_sex: subjects sorted in separate sex groups
    :return: file name (without folder)
    """
    methods = '+'.join(safe_name(m) for m in dict.fromkeys(df['method'].dropna())) \
        if 'method' in df.columns and df['method'].notna().any() else 'unknown'
    datasets = '+'.join(safe_name(d) for d in dict.fromkeys(df['dataset']))
    sort_part = 'height' if sort_by == 'height' else 'cervical_length'
    stratified = '_stratified_by_sex' if stratify_by_sex else ''
    return (f'figure_spinal_levels_{distance}_distance_{FIRST_LEVEL}-{LAST_LEVEL}_method_{methods}'
            f'_datasets_{datasets}_sorted_by_{sort_part}{stratified}.png')


def main():
    parser = get_parser()
    args = parser.parse_args()
    fnames_table = [os.path.abspath(os.path.expanduser(fname)) for fname in args.i]
    out_dir = os.path.abspath(args.output_folder) if args.output_folder else os.path.dirname(fnames_table[0])
    os.makedirs(out_dir, exist_ok=True)

    df = load_tables(fnames_table, parser, args.session)
    try:
        distance = get_distance(df, args.distance)
    except ValueError as err:
        parser.error(str(err))
    dist_col = DISTANCE_COL[distance]
    if dist_col not in df.columns:
        parser.error(f'None of the tables has a {dist_col} column (distance "{distance}").')

    # Rows without a distance cannot be plotted (e.g. rows of a table with the other distance type)
    no_distance = df[dist_col].isna()
    if no_distance.any():
        print(f'WARNING: {int(no_distance.sum())} row(s) without {dist_col} are not plotted: '
              f'{df.loc[no_distance, "subject"].unique().tolist()}')
        df = df[~no_distance].reset_index(drop=True)

    # Subjects without height: left out with -exclude-missing-height, otherwise plotted (at the end by height)
    no_height = pd.to_numeric(df[HEIGHT_COL], errors='coerce').isna()
    if no_height.any():
        if args.exclude_missing_height:
            print(f'INFO: {int(no_height.sum())} row(s) without height are not plotted: '
                  f'{df.loc[no_height, "subject"].unique().tolist()}')
            df = df[~no_height].reset_index(drop=True)
        else:
            print(f'INFO: {int(no_height.sum())} row(s) without height are plotted'
                  f'{" at the end of the x-axis" if args.sort_by == "height" else ""} '
                  f'(use -exclude-missing-height to leave them out).')

    if df.empty:
        parser.error(f'No rows with {dist_col} to plot.')
    print(f'Plotting {len(df)} row(s), {df["subject"].nunique()} subject(s) from {len(fnames_table)} table(s), '
          f'datasets: {", ".join(map(str, df["dataset"].unique()))}')

    # Figure name: -figure-name, or built from the distance, method(s), plotted datasets and sort order
    # (e.g. figure_spinal_levels_total_distance_2-8_method_rootlets+centerline_datasets_ds1+uk_sorted_by_height.png)
    if args.figure_name:
        fname_figure = os.path.join(out_dir, args.figure_name)
    else:
        fname_figure = os.path.join(out_dir, default_figure_name(df, distance, args.sort_by, args.stratify_by_sex))
    print(f'Subjects sorted by {args.sort_by}{" within each sex group" if args.stratify_by_sex else ""}.')
    generate_distance_figure(df, fname_figure, distance, show=not args.no_show, sort_by=args.sort_by,
                             marker_edge_width=args.marker_edge_width, stratify_by_sex=args.stratify_by_sex)


if __name__ == '__main__':
    main()