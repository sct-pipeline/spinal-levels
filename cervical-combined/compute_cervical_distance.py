"""
This script computes the distance between the C2 and C8 spinal levels for each subject and saves it to one CSV table
per dataset. The figure is generated separately by `plot_cervical_distance.py`, which takes one or more of these
per-dataset tables and plots them together.

Each dataset can come from one of two sources:
1. Per-level CSV files generated by the rootlets_to_spinal_levels.py script (spinal levels estimated using rootlets or
   PAM50, `-method`). Two distances are supported (`-distance`):
   - midpoint: C8 midpoint distance from the reference minus C2 midpoint distance from the reference
   - total: C8 end (bottom) distance from the reference minus C2 start (top) distance from the reference
2. A final table (CSV or TSV, one row per subject/session) with the columns:
       subject, session, slice_top_C2_I-S, slice_bottom_C8_I-S, length_C2-C8_centerline_mm, sex, age
   Only `subject` and `length_C2-C8_centerline_mm` are required; the other columns are used when present.
   The centerline length (top C2 - bottom C8) is used as the total distance, so only `-distance total` is supported.
   The final table is used automatically when available: when an `-i` entry is the table file itself, or when a
   CSV/TSV file with these columns is found in the `-i` folder. Use `-ignore-final-table` to always use the per-level
   CSV files for folders.

Multiple datasets are supported: pass one results folder (or final table) per dataset to `-i` and the matching
participants.tsv files (same order) to `-participants`; pass `none` for a dataset without participants.tsv (e.g. when
its final table already has sex and age). The height column can be named 'height (cm)', 'height_cm' or 'height'
(heights in meters are converted to cm automatically). Sex and age from the final table take precedence; missing values
are filled from participants.tsv. Height always comes from participants.tsv.

Subjects with missing sex or height are excluded from the tables (use `-allow-missing-height` to keep subjects
without height); a summary of included/excluded rows per dataset is printed.

Optionally (`-analyse-pmj-to-conus`), the per-subject PMJ-to-conus distances (files `*_pmj_to_conus_distance.csv`)
are aggregated into one table per dataset, with sex and height, without subjects missing height or sex.

No table combining all datasets is saved: each dataset gets its own files.

Example:
    python compute_cervical_distance.py \
        -i ~/results/data-multi-subject ~/results/dataset2/final_table.csv \
        -participants ~/data/data-multi-subject/participants.tsv none \
        -method rootlets \
        -analyse-pmj-to-conus

    python plot_cervical_distance.py \
        -i figures-and-dataframes/spinal_levels_total_distance_2-8_ref_c2_method_rootlets_data-multi-subject.csv \
           figures-and-dataframes/spinal_levels_total_distance_2-8_method_centerline_dataset2.csv

Output (per dataset):
- CSV file with the per-level spinal level estimation of all subjects (per-level CSV files only)
- CSV file with the distance between the C2 and C8 levels for each subject (one row per subject/session), with sex,
  age and height, without excluded subjects (input of plot_cervical_distance.py)
- With -analyse-pmj-to-conus: CSV file with the PMJ-to-conus distance for each subject, with sex and height, without
  subjects missing height or sex

The script was inspired by script '03a_generate_figure_inter_rater_variablity-PMJ_COV.py':
https://github.com/ivadomed/model-spinal-rootlets/blob/main/inter-rater_variability/03a_generate_figure_inter_rater_variablity-PMJ_COV.py
"""

import os
import glob
import argparse

import numpy as np
import pandas as pd


# Levels used for the distance computation: C2 and C8
FIRST_LEVEL = 2
LAST_LEVEL = 8

# Methods for spinal level estimation
METHODS = ['rootlets', 'PAM50']

# Column with the per-subject distance for each distance type
DISTANCE_COL = {'midpoint': 'midpoints_distance_mm', 'total': 'total_distance_mm'}

# Suffix of the per-subject CSV files with the PMJ-to-conus distance
PMJ_TO_CONUS_SUFFIX = '_pmj_to_conus_distance.csv'

# Final table (one row per subject/session) with the C2-C8 centerline length
FINAL_TABLE_LENGTH_COL = 'length_C2-C8_centerline_mm'
FINAL_TABLE_REQUIRED_COLUMNS = ['subject', FINAL_TABLE_LENGTH_COL]
FINAL_TABLE_OPTIONAL_COLUMNS = ['session', 'slice_top_C2_I-S', 'slice_bottom_C8_I-S', 'sex', 'age']
# Method label used for datasets coming from a final table
FINAL_TABLE_METHOD = 'centerline'

# Default participants.tsv with the subject sex and height (first dataset)
PARTICIPANTS_TSV = os.path.expanduser('~/data/data.neuro.polymtl.ca/data-multi-subject/participants.tsv')

# Accepted names of the height column in participants.tsv (first match is used)
HEIGHT_COLUMNS = ['height (cm)', 'height_cm', 'height']
# Unified height column used internally (always in cm)
HEIGHT_COL = 'height_cm'

# Subject information taken from participants.tsv and/or the final table
PARTICIPANT_INFO_COLUMNS = ['sex', 'age', HEIGHT_COL]


