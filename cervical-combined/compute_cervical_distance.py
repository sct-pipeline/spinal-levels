def normalize_sex(series):
    """
    Normalize sex values to 'F' / 'M' (e.g. 'female', 'f', 'Male' -> 'F', 'F', 'M'); anything else becomes NaN.
    """
    sex = series.astype(str).str.strip().str.upper().str[0]
    return sex.where(sex.isin(['F', 'M']))


def read_table(fname):
    """
    Read a CSV or TSV file (separator chosen from the extension), with stripped column names.
    """
    df = pd.read_csv(fname, sep='\t' if fname.lower().endswith('.tsv') else ',')
    df.columns = df.columns.str.strip()
    return df


def load_participants(fname_participants):
    """
    Load participants.tsv and return a dataframe with unified columns: participant_id, sex ('F', 'M' or NaN), age
    (numeric) and height_cm (numeric, in cm). The height column can be named 'height (cm)', 'height_cm' or 'height'.
    :param fname_participants: path to participants.tsv, or None (returns an empty dataframe)
    :return: dataframe with columns participant_id, sex, age, height_cm
    """
    columns = ['participant_id'] + PARTICIPANT_INFO_COLUMNS
    if fname_participants is None:
        return pd.DataFrame(columns=columns)

    df = pd.read_csv(fname_participants, sep='\t')
    if 'participant_id' not in df.columns:
        raise ValueError(f'No "participant_id" column in {fname_participants}.')

    # Height: use the first matching column, convert to numeric ('n/a' etc. become NaN)
    height_col = next((col for col in HEIGHT_COLUMNS if col in df.columns), None)
    if height_col is None:
        print(f'WARNING: no height column ({HEIGHT_COLUMNS}) in {fname_participants}; height will be unknown.')
        df[HEIGHT_COL] = np.nan
    else:
        df[HEIGHT_COL] = pd.to_numeric(df[height_col], errors='coerce')
        # Heights stored in meters (e.g. 1.75) are converted to cm
        if df[HEIGHT_COL].notna().any() and df[HEIGHT_COL].median() < 3:
            print(f'INFO: height in {fname_participants} looks like meters; converting to cm.')
            df[HEIGHT_COL] = df[HEIGHT_COL] * 100

    if 'sex' in df.columns:
        df['sex'] = normalize_sex(df['sex'])
    else:
        print(f'WARNING: no "sex" column in {fname_participants}; sex will be unknown.')
        df['sex'] = np.nan

    df['age'] = pd.to_numeric(df['age'], errors='coerce') if 'age' in df.columns else np.nan

    return df[columns]


def add_participant_info(df, df_participants, fname_participants, dataset):
    """
    Add sex, age and height from participants.tsv to the per-subject dataframe. Values already in `df` (e.g. sex and
    age from a final table) take precedence; missing values are filled from participants.tsv.
    :param df: dataframe with one row per subject (or subject/session) and a 'subject' column
    :param df_participants: dataframe returned by load_participants()
    :param fname_participants: path to participants.tsv (None if not provided), used in the messages
    :param dataset: dataset name, used in the messages
    :return: dataframe with 'sex', 'age' and HEIGHT_COL columns
    """
    df = df.merge(df_participants, how='left', left_on='subject', right_on='participant_id',
                  suffixes=('', '_participants'))
    for col in PARTICIPANT_INFO_COLUMNS:
        col_participants = f'{col}_participants'
        if col_participants not in df.columns:
            continue
        if col == 'sex':
            both = df[col].notna() & df[col_participants].notna()
            mismatch = both & (df[col] != df[col_participants])
            if mismatch.any():
                print(f'WARNING: sex in the final table differs from {fname_participants} for '
                      f'{df.loc[mismatch, "subject"].unique().tolist()} ({dataset}); the final table value is used.')
        df[col] = df[col].fillna(df[col_participants])
        df = df.drop(columns=col_participants)

    if fname_participants is not None:
        not_found = df.loc[df['participant_id'].isna(), 'subject'].unique().tolist()
        if not_found:
            print(f'WARNING: {len(not_found)} subject(s) of {dataset} not found in {fname_participants}: '
                  f'{not_found}')
    return df


def find_final_tables(path, out_dir):
    """
    Find the final table(s) of one dataset: `path` itself if it is a file, otherwise all CSV/TSV files in the folder
    (recursively) whose header contains FINAL_TABLE_REQUIRED_COLUMNS. Files in the output folder are skipped (so that
    tables saved by this script are not read back).
    :param path: -i entry (folder or file)
    :param out_dir: output folder of this script
    :return: list of paths (empty if none found)
    """
    if os.path.isfile(path):
        cols = read_table(path).columns
        missing = [col for col in FINAL_TABLE_REQUIRED_COLUMNS if col not in cols]
        if missing:
            raise ValueError(f'{path} is a file but lacks the final table column(s) {missing}.')
        return [path]

    candidates = sorted(glob.glob(os.path.join(path, '**', '*.csv'), recursive=True) +
                        glob.glob(os.path.join(path, '**', '*.tsv'), recursive=True))
    found = []
    for fname in candidates:
        if os.path.abspath(fname).startswith(out_dir + os.sep) or fname.endswith(PMJ_TO_CONUS_SUFFIX):
            continue
        try:
            header = pd.read_csv(fname, sep='\t' if fname.lower().endswith('.tsv') else ',', nrows=0).columns
        except Exception:
            continue
        if all(col in header.str.strip() for col in FINAL_TABLE_REQUIRED_COLUMNS):
            found.append(fname)
    return found


def load_final_table(fnames, dataset):
    """
    Load the final table(s) of one dataset (one row per subject/session) and use the centerline length
    (`length_C2-C8_centerline_mm`) as the total C2-C8 distance.
    :param fnames: list of paths to the final table(s)
    :param dataset: dataset name (used in the 'dataset' column and the messages)
    :return: dataframe with one row per subject/session and 'method', 'dataset' and 'source' columns
    """
    df = pd.concat([read_table(fname) for fname in fnames], ignore_index=True).drop_duplicates()
    df['subject'] = df['subject'].astype(str).str.strip()
    for col in FINAL_TABLE_OPTIONAL_COLUMNS:
        if col not in df.columns:
            df[col] = np.nan
    df['sex'] = normalize_sex(df['sex'])
    df['age'] = pd.to_numeric(df['age'], errors='coerce')
    df[DISTANCE_COL['total']] = pd.to_numeric(df[FINAL_TABLE_LENGTH_COL], errors='coerce')

    n_missing = int(df[DISTANCE_COL['total']].isna().sum())
    if n_missing:
        print(f'WARNING: {n_missing} row(s) of {dataset} without {FINAL_TABLE_LENGTH_COL}; the distance will be NaN.')
    duplicated = df.duplicated(subset=['subject', 'session'], keep=False)
    if duplicated.any():
        print(f'WARNING: more than one row for subject/session {df.loc[duplicated, "subject"].unique().tolist()} '
              f'in {dataset}; all rows are kept.')

    df = df.sort_values(by=['subject', 'session']).reset_index(drop=True)
    df['first_level'] = FIRST_LEVEL
    df['last_level'] = LAST_LEVEL
    df['method'] = FINAL_TABLE_METHOD
    df['dataset'] = dataset
    df['source'] = 'final_table'

    print(f'Final table ({len(fnames)} file(s), {len(df)} row(s), {df["subject"].nunique()} subject(s), {dataset}) '
          f'loaded.')
    print(df[['subject', DISTANCE_COL['total']]].describe())
    return df


def compute_midpoints_distance(df, reference, first_level=FIRST_LEVEL, last_level=LAST_LEVEL):
    """
    Compute the distance between the midpoints of `first_level` and `last_level` for each subject as
    `distance_from_{reference}_midpoint` of `last_level` minus `distance_from_{reference}_midpoint` of `first_level`.
    :param df: dataframe with per-level distances from the reference point
    :param reference: reference point for distance computation
    :param first_level: first spinal level
    :param last_level: last spinal level
    :return: dataframe with one row per subject
    """
    added_ref = f'{reference}_top' if reference == 'c2' else reference
    df_pivot = df.pivot_table(index='subject', columns='spinal_level', values=f'distance_from_{added_ref}_midpoint')

    rows = []
    for subject, row in df_pivot.iterrows():
        midpoint_first = row.get(first_level, np.nan)
        midpoint_last = row.get(last_level, np.nan)
        missing = [level for level, midpoint in [(first_level, midpoint_first), (last_level, midpoint_last)]
                   if np.isnan(midpoint)]
        if missing:
            print(f"WARNING: {subject} is missing level(s) {','.join(map(str, missing))}; "
                  f"the distance between the midpoints will be NaN.")

        rows.append({
            'subject': subject,
            'first_level': first_level,
            'last_level': last_level,
            f'distance_from_{added_ref}_midpoint_first_level_mm': midpoint_first,
            f'distance_from_{added_ref}_midpoint_last_level_mm': midpoint_last,
            'midpoints_distance_mm': midpoint_last - midpoint_first
        })

    return pd.DataFrame(rows)


def compute_total_distance(df, reference, first_level=FIRST_LEVEL, last_level=LAST_LEVEL):
    """
    Compute the total distance between the top (start) of `first_level` and the bottom (end) of `last_level` for each
    subject as `distance_from_{reference}_end_S-I` of `last_level` minus `distance_from_{reference}_start_S-I` of
    `first_level`.
    :param df: dataframe with per-level distances from the reference point
    :param reference: reference point for distance computation
    :param first_level: first spinal level
    :param last_level: last spinal level
    :return: dataframe with one row per subject
    """
    added_ref = f'{reference}_top' if reference == 'c2' else reference
    df_start = df.pivot_table(index='subject', columns='spinal_level', values=f'distance_from_{added_ref}_start_S-I')
    df_end = df.pivot_table(index='subject', columns='spinal_level', values=f'distance_from_{added_ref}_end_S-I')

    rows = []
    for subject in df_start.index.union(df_end.index):
        start_first = df_start.loc[subject].get(first_level, np.nan) if subject in df_start.index else np.nan
        end_last = df_end.loc[subject].get(last_level, np.nan) if subject in df_end.index else np.nan
        missing = [level for level, value in [(first_level, start_first), (last_level, end_last)] if pd.isna(value)]
        if missing:
            print(f"WARNING: {subject} is missing level(s) {','.join(map(str, missing))}; "
                  f"the total distance will be NaN.")

        rows.append({
            'subject': subject,
            'first_level': first_level,
            'last_level': last_level,
            f'distance_from_{added_ref}_start_first_level_mm': start_first,
            f'distance_from_{added_ref}_end_last_level_mm': end_last,
            'total_distance_mm': end_last - start_first
        })

    return pd.DataFrame(rows)


def load_spinal_levels(dir_path, reference, method, out_dir, dataset):
    """
    Load and aggregate the per-subject CSV files generated by the rootlets_to_spinal_levels.py script for one method
    and one dataset.
    :param dir_path: path to the folder with the per-subject CSV files
    :param reference: reference point for distance computation
    :param method: method for spinal level estimation
    :param out_dir: path to the output folder where the aggregated CSV file will be saved
    :param dataset: dataset name (used in the output file name)
    :return: dataframe with one row per subject and spinal level (C2-C8)
    """
    # Get all the CSV files generated by the rootlets_to_spinal_levels.py script
    csv_files = glob.glob(os.path.join(dir_path, '**', f'*{reference}_distance_{method}*.csv'), recursive=True)
    if not csv_files:
        raise FileNotFoundError(f'No *{reference}_distance_{method}*.csv files (and no final table) found in '
                                f'{dir_path}. Check the -i path.')

    # Loop across CSV files and aggregate the results into one dataframe
    df = pd.concat([pd.read_csv(csv_file) for csv_file in csv_files])

    # Extract subjectID from the fname and add it as a column
    df['subject'] = df['fname'].apply(lambda x: x.split('_')[0])

    # Extract spinal levels (cervical '2-8')
    df = df[df['spinal_level'].isin([2, 3, 4, 5, 6, 7, 8])]

    # sort df by subject and spinal level
    df = df.sort_values(by=['subject', 'spinal_level'])

    # Save dataframe with all subjects of this dataset to CSV file
    fname_out = os.path.join(out_dir, f'spinal_levels_ref_{reference}_method_{method}_{dataset}.csv')
    df.to_csv(fname_out, index=False)
    print(f'CSV file saved in {fname_out}.')

    return df


def load_pmj_to_conus(dir_path, dataset):
    """
    Load and aggregate the per-subject PMJ-to-conus distance CSV files (`*_pmj_to_conus_distance.csv`) of one dataset
    into one table.
    :param dir_path: path to the folder with the per-subject CSV files
    :param dataset: dataset name (used in the 'dataset' column and the messages)
    :return: dataframe with all rows of all per-subject files plus 'subject' and 'dataset' columns, or None if no
    files were found
    """
    if not os.path.isdir(dir_path):
        print(f'WARNING: {dir_path} is a file, not a folder; skipping PMJ-to-conus for {dataset}.')
        return None
    csv_files = sorted(glob.glob(os.path.join(dir_path, '**', f'*{PMJ_TO_CONUS_SUFFIX}'), recursive=True))
    if not csv_files:
        print(f'WARNING: no *{PMJ_TO_CONUS_SUFFIX} files found in {dir_path}; skipping PMJ-to-conus for {dataset}.')
        return None

    list_df = []
    for csv_file in csv_files:
        df_file = pd.read_csv(csv_file)
        # Subject ID from the file name (e.g. sub-001_T2w_pmj_to_conus_distance.csv -> sub-001)
        df_file['subject'] = os.path.basename(csv_file).split('_')[0]
        list_df.append(df_file)
    df = pd.concat(list_df, ignore_index=True)
    df['dataset'] = dataset

    # subject and dataset as the first columns, sorted by subject
    df = df[['subject', 'dataset'] + [col for col in df.columns if col not in ('subject', 'dataset')]]
    df = df.sort_values(by='subject').reset_index(drop=True)

    duplicated = df.loc[df['subject'].duplicated(), 'subject'].unique().tolist()
    if duplicated:
        print(f'WARNING: more than one PMJ-to-conus row for subject(s) {duplicated} in {dataset} '
              f'(e.g. several sessions/runs); all rows are kept.')

    print(f'PMJ-to-conus distance ({len(csv_files)} file(s), {df["subject"].nunique()} subject(s), {dataset}) '
          f'loaded.')
    print(df.describe())

    return df


def compute_distance(df, reference, method, distance, dataset):
    """
    Compute the per-subject distance (midpoint or total) between FIRST_LEVEL and LAST_LEVEL.
    :param df: dataframe returned by load_spinal_levels()
    :param reference: reference point for distance computation
    :param method: method for spinal level estimation
    :param distance: distance to compute ('midpoint' or 'total')
    :param dataset: dataset name (used in the 'dataset' column and the messages)
    :return: dataframe with one row per subject and 'method', 'dataset' and 'source' columns
    """
    if distance == 'midpoint':
        df_distance = compute_midpoints_distance(df, reference, FIRST_LEVEL, LAST_LEVEL)
    else:
        df_distance = compute_total_distance(df, reference, FIRST_LEVEL, LAST_LEVEL)
    print(f'{distance.capitalize()} distance between levels {FIRST_LEVEL} and {LAST_LEVEL} ({method}, {dataset}) '
          f'computed.')
    print(df_distance[['subject', DISTANCE_COL[distance]]].describe())

    df_distance['session'] = np.nan
    df_distance['method'] = method
    df_distance['dataset'] = dataset
    df_distance['source'] = 'spinal_levels'
    return df_distance


def distance_table_fname(out_dir, distance, reference, method, dataset):
    """
    Path of the per-dataset C2-C8 distance table (input of plot_cervical_distance.py). Tables from a final table have
    no reference in their name.
    """
    ref_part = '' if method == FINAL_TABLE_METHOD else f'_ref_{reference}'
    return os.path.join(out_dir, f'spinal_levels_{distance}_distance_{FIRST_LEVEL}-{LAST_LEVEL}'
                                 f'{ref_part}_method_{method}_{dataset}.csv')


def exclude_and_summarize(df_all, dataset_names, title='Subjects summary', require_height=True):
    """
    Exclude rows with missing sex (and height, if `require_height`) and print, per dataset and in total, how many rows
    (subjects/sessions) were excluded (and why) and how many were used (females/males).
    :param df_all: dataframe with 'dataset', 'subject', 'sex' and HEIGHT_COL columns (one or more datasets)
    :param dataset_names: dataset names in the order of -i
    :param title: title of the printed summary
    :param require_height: exclude rows with missing height
    :return: dataframe with the included rows only
    """
    missing_sex = df_all['sex'].isna()
    missing_height = df_all[HEIGHT_COL].isna()
    excluded = missing_sex | missing_height if require_height else missing_sex
    df_used = df_all[~excluded].reset_index(drop=True)

    print(f'\n=== {title} ===')
    for dataset in list(dataset_names) + ['TOTAL']:
        mask = df_all['dataset'] == dataset if dataset != 'TOTAL' else pd.Series(True, index=df_all.index)
        df_ds_used = df_all[mask & ~excluded]
        n_f = int((df_ds_used['sex'] == 'F').sum())
        n_m = int((df_ds_used['sex'] == 'M').sum())
        print(f'{dataset}: {int(mask.sum())} rows with results -> {len(df_ds_used)} used '
              f'({n_f} females, {n_m} males; {df_ds_used["subject"].nunique()} unique subjects); '
              f'excluded {int((mask & excluded).sum())} '
              f'(missing sex: {int((mask & missing_sex).sum())}, missing height: {int((mask & missing_height).sum())}'
              f'{"" if require_height else ", kept"})')
        if dataset != 'TOTAL' and (mask & excluded).any():
            print(f'    excluded subjects: {df_all.loc[mask & excluded, "subject"].unique().tolist()}')
    print()
    return df_used


def main():
    parser = get_parser()
    args = parser.parse_args()
    reference = args.reference
    distance = args.distance
    method = args.method
    out_dir = os.path.abspath(args.output_folder)
    os.makedirs(out_dir, exist_ok=True)

    # Pair each -i entry with its participants.tsv (or None) and name
    input_paths = [os.path.abspath(os.path.expanduser(path)) for path in args.i]
    participants_files = [None if path.lower() == 'none' else os.path.expanduser(path) for path in args.participants]
    if len(participants_files) != len(input_paths):
        parser.error(f'-i has {len(input_paths)} entry(ies) but -participants has {len(participants_files)}; pass '
                     f'one participants.tsv (or "none") per dataset, in the same order.')
    if args.dataset_names is None:
        dataset_names = [os.path.basename(os.path.dirname(os.path.abspath(fname))) if fname is not None
                         else os.path.splitext(os.path.basename(path))[0]
                         for fname, path in zip(participants_files, input_paths)]
    else:
        dataset_names = args.dataset_names
    if len(dataset_names) != len(input_paths) or len(set(dataset_names)) != len(dataset_names):
        parser.error('-dataset-names must give one unique name per dataset (same order as -i).')

    # Final table(s) of each dataset (empty list -> per-level CSV files are used)
    final_tables = {}
    for path, dataset in zip(input_paths, dataset_names):
        if os.path.isdir(path) and args.ignore_final_table:
            final_tables[dataset] = []
        else:
            final_tables[dataset] = find_final_tables(path, out_dir)
    if distance == 'midpoint' and any(final_tables.values()):
        parser.error(f'Final table(s) found for {[ds for ds, f in final_tables.items() if f]}, but they only provide '
                     f'the total C2-C8 length; use -distance total (or -ignore-final-table for folders).')

    # Compute the distance between the C2 and C8 levels for each dataset
    list_df_distance = []
    list_df_conus = []
    for path, fname_participants, dataset in zip(input_paths, participants_files, dataset_names):
        print(f'\n=== Dataset: {dataset} ({path}) ===')
        df_participants = load_participants(fname_participants)
        if final_tables[dataset]:
            print(f'Using final table(s): {final_tables[dataset]}')
            df_distance = load_final_table(final_tables[dataset], dataset)
        else:
            df = load_spinal_levels(path, reference, method, out_dir, dataset)
            df_distance = compute_distance(df, reference, method, distance, dataset)
        df_distance = add_participant_info(df_distance, df_participants, fname_participants, dataset)
        list_df_distance.append(df_distance)

        # PMJ-to-conus distance (independent of the spinal level method)
        if args.analyse_pmj_to_conus:
            df_conus = load_pmj_to_conus(path, dataset)
            if df_conus is not None:
                # Add sex, age and height (used to exclude subjects without them)
                df_conus = df_conus.drop(columns=PARTICIPANT_INFO_COLUMNS, errors='ignore')
                df_conus = add_participant_info(df_conus, df_participants, fname_participants, dataset)
                list_df_conus.append(df_conus)

    # PMJ-to-conus: exclude subjects missing height or sex and save one table per dataset
    if args.analyse_pmj_to_conus:
        if list_df_conus:
            df_conus_all = pd.concat(list_df_conus, ignore_index=True)
            df_conus_all = exclude_and_summarize(df_conus_all, dataset_names, title='PMJ-to-conus subjects summary',
                                                 require_height=not args.allow_missing_height)
            for dataset in df_conus_all['dataset'].unique():
                df_conus_ds = df_conus_all[df_conus_all['dataset'] == dataset]
                fname_conus = os.path.join(out_dir, f'pmj_to_conus_distance_{dataset}.csv')
                df_conus_ds.to_csv(fname_conus, index=False)
                print(f'PMJ-to-conus CSV ({dataset}, {len(df_conus_ds)} row(s)) saved in {fname_conus}.')
        else:
            print(f'\nWARNING: no *{PMJ_TO_CONUS_SUFFIX} files found in any dataset; no PMJ-to-conus table saved.')

    # Add the common columns, exclude subjects with missing sex (and height) and print a summary
    df_all = pd.concat(list_df_distance, ignore_index=True)
    df_all['subject_key'] = df_all['dataset'] + '/' + df_all['subject']
    has_session = df_all['session'].notna()
    df_all.loc[has_session, 'subject_key'] += '/' + df_all.loc[has_session, 'session'].astype(str)
    df_all['distance_type'] = distance
    df_all['reference'] = np.where(df_all['source'] == 'final_table', 'none', reference)
    df_all = exclude_and_summarize(df_all, dataset_names, require_height=not args.allow_missing_height)

    # Save one table per dataset (no table combining all datasets)
    fnames_saved = []
    for dataset in dataset_names:
        df_ds = df_all[df_all['dataset'] == dataset].reset_index(drop=True)
        if df_ds.empty:
            print(f'WARNING: no rows left for {dataset} after the exclusions; no table saved.')
            continue
        method_ds = df_ds['method'].iloc[0]
        fname_ds = distance_table_fname(out_dir, distance, reference, method_ds, dataset)
        df_ds.to_csv(fname_ds, index=False)
        fnames_saved.append(fname_ds)
        print(f'{distance.capitalize()} distance {FIRST_LEVEL}-{LAST_LEVEL} ({method_ds}, {dataset}, {len(df_ds)} '
              f'row(s)) saved in {fname_ds}.')

    if fnames_saved:
        print(f'\nPlot with: python plot_cervical_distance.py -i {" ".join(fnames_saved)}')


if __name__ == '__main__':
    main()