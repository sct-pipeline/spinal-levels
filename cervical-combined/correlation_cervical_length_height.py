"""
This script plots the correlation between the C2-C8 distance (midpoints or total) and subject height, for one or more
datasets combined in one figure, and compares the C2-C8 distance (and height) between males and females.

Optionally (`-pmj-to-conus`), it also plots the correlation between the PMJ-to-conus length (spinal cord length) and
  - subject height
  - the C2-C8 (cervical) length
and compares the PMJ-to-conus length between males and females.

The correlation figures use the shared plotting conditions of visualisation_utils.py (plot_correlation): font, sex
colors, fixed marker per dataset name, marker sizes, linear fit with its 95% CI band, Spearman text and legend.

Input:
- One or more CSV tables with the C2-C8 distance per subject (`-i`), combined into one analysis, e.g. the per-dataset
  tables generated by compute_cervical_distance.py:
      spinal_levels_total_distance_2-8_ref_c2_method_PAM50_<dataset>.csv
  They already contain the 'dataset', 'sex' and 'height_cm' columns. Final tables (subject, session, ...,
  length_C2-C8_centerline_mm, sex, age, dataset) can also be passed directly: `length_C2-C8_centerline_mm` is used as
  the total C2-C8 distance. The column separator (',', ';' or tab) is detected per file.
  Tables with a "session" column keep only the rows of `-session` (default ses-A; "all" keeps every session). Rows
  present in more than one table (same dataset/subject/session) are kept only once (first table wins).
  All tables must contain the same distance type (midpoint or total), unless `-distance` is given explicitly.
- (Optional, for tables without sex or height) participants.tsv file(s) via -participants: one file used for all
  tables, or one per table (same order as -i, "none" for a table that does not need one). Values missing in a table
  are filled from its participants.tsv.
- (Optional) One or more PMJ-to-conus CSV files generated by compute_cervical_distance.py with -analyse-pmj-to-conus
  (pmj_to_conus_distance_<dataset>.csv), via -pmj-to-conus. The distance column is detected automatically (or set
  with -conus-col); values in mm are converted to cm. Subjects are matched on 'dataset' and 'subject'. Only subjects
  present in the C2-C8 tables (with sex and height) are used.

Subjects without sex or height are excluded (they cannot be used for the correlation with height); the number of
excluded subjects per dataset is printed.

Output (saved to the output folder):
    - figure_correlation_cervical_<distance>_<reference>_distance_2-8_height_<method>_datasets_<datasets>.png:
      scatter plot (color = sex, marker = dataset) with a linear fit across all subjects (visual guide) and the
      Spearman correlation (all subjects pooled and per dataset)
    - With -pmj-to-conus:
        - figure_correlation_pmj_to_conus_length_height_datasets_<datasets>.png
        - figure_correlation_pmj_to_conus_length_cervical_<distance>_<reference>_distance_2-8_<method>_datasets_<datasets>.png
    - Printed to the terminal: Spearman correlations (pooled and per dataset) and male vs female comparison
      (Mann-Whitney U test) of the C2-C8 distance, height (and PMJ-to-conus length), all subjects pooled and per
      dataset
    <method>, <reference> and <datasets> list all methods/references/datasets of the combined tables, joined with '+'.

Spearman correlation is used because the distance is not normally distributed (Shapiro-Wilk test) and the sample is
small, so a single subject can strongly influence the Pearson correlation. For the same reason, males and females are
compared with the non-parametric Mann-Whitney U test (with the rank-biserial correlation as effect size) instead of
the t-test.

Example:
    python 05_correlation_cervical_length_height.py \
        -i figures-and-dataframes/spinal_levels_total_distance_2-8_ref_c2_method_PAM50_data-multi-subject.csv \
           figures-and-dataframes/spinal_levels_total_distance_2-8_ref_c2_method_PAM50_dataset2.csv \
        -pmj-to-conus figures-and-dataframes/pmj_to_conus_distance_data-multi-subject.csv \
                      figures-and-dataframes/pmj_to_conus_distance_dataset2.csv

Author: Jan Valosek
"""

import os
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats
# Shared plotting conditions and correlation helpers, same in all figure scripts
from visualisation_utils import get_dataset_markers, plot_correlation, spearman_ci, format_p

# Unified height column (in cm) written by compute_cervical_distance.py
HEIGHT_COL = 'height_cm'
# Accepted height column names in participants.tsv (only used with -participants)
HEIGHT_COLUMNS = ['height (cm)', 'height_cm', 'height']

# Column with the per-subject C2-C8 distance for each distance type (as written by compute_cervical_distance.py)
DISTANCE_COL = {'midpoint': 'midpoints_distance_mm', 'total': 'total_distance_mm'}
# Centerline length column of the final tables, used as the total C2-C8 distance
FINAL_TABLE_LENGTH_COL = 'length_C2-C8_centerline_mm'
# Candidate column separators, detected per file from its header line
SEPARATORS = [',', ';', '\t']

# Internal columns (in cm)
C2C8_COL = 'c2c8_cm'
CONUS_COL = 'pmj_to_conus_cm'

# Sexes used in the analyses (sex colors, labels and dataset markers are defined in visualisation_utils.py)
SEXES = ['F', 'M']


def detect_separator(fname):
    """
    Detect the column separator of a CSV/TSV file (',', ';' or tab) from its header line: the candidate that occurs
    most often wins (',' if none occurs).
    """
    with open(fname, encoding='utf-8-sig') as f:
        header = f.readline()
    counts = {sep: header.count(sep) for sep in SEPARATORS}
    sep = max(counts, key=counts.get)
    return sep if counts[sep] > 0 else ','


def read_table(fname):
    """
    Read a CSV/TSV file with an auto-detected separator, with stripped column names.
    """
    df = pd.read_csv(fname, sep=detect_separator(fname), encoding='utf-8-sig')
    df.columns = df.columns.str.strip()
    return df


def normalize_sex(series):
    """
    Normalize sex values to 'F' / 'M' (e.g. 'female', 'f', 'Male' -> 'F', 'F', 'M'); anything else becomes NaN.
    """
    sex = series.astype(str).str.strip().str.upper().str[0]
    return sex.where(sex.isin(SEXES))


def spearman_summary(x, y, label):
    """
    Compute the Spearman correlation with its 95% CI, print it and return a one-line string for the figure.
    """
    n = len(x)
    if n < 4:
        print(f'{label}: n = {n}, too few subjects for the Spearman correlation.')
        return f'{label}: n = {n}'
    rho, p = stats.spearmanr(x, y)
    rho_lo, rho_hi = spearman_ci(rho, n)
    print(f'{label}: n = {n}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], {format_p(p)}')
    return f'{label} (n = {n}): ρ = {rho:.2f} [{rho_lo:.2f}, {rho_hi:.2f}], {format_p(p)}'


def correlation_analysis(df, x_col, y_col, title, datasets):
    """
    Print the Shapiro-Wilk normality tests and the Spearman correlation between `x_col` and `y_col`, all subjects
    pooled and per dataset.
    :param df: dataframe with one row per subject (no missing values in x_col and y_col)
    """
    print(f'\n=== Correlation: {title} ===')
    if len(df) >= 3:
        print(f'Shapiro-Wilk normality test: {x_col} p = {stats.shapiro(df[x_col]).pvalue:.3f}, '
              f'{y_col} p = {stats.shapiro(df[y_col]).pvalue:.3f}')
    spearman_summary(df[x_col], df[y_col], 'All')
    if len(datasets) > 1:
        for dataset in datasets:
            mask = df['dataset'] == dataset
            spearman_summary(df.loc[mask, x_col], df.loc[mask, y_col], dataset)


def compare_sex(values, sex, label, unit='cm'):
    """
    Compare a measure between females and males with the two-sided Mann-Whitney U test (non-parametric, does not
    assume normality). The effect size is the rank-biserial correlation r = 2U / (n_F * n_M) - 1, where U is the
    statistic of the female group: r > 0 means females tend to have higher values, r < 0 means males do
    (|r| ~0.1 small, ~0.3 medium, ~0.5 large).
    :param values: pd.Series with the measure (e.g., C2-C8 distance in cm or height in cm)
    :param sex: pd.Series with 'F'/'M' (same index as values)
    :param label: label for the printout (e.g., 'All' or the dataset name)
    :param unit: unit of the measure for the printout
    :return: dict with the test results, or None if there are too few subjects
    """
    values_f = values[sex == 'F'].dropna()
    values_m = values[sex == 'M'].dropna()
    n_f, n_m = len(values_f), len(values_m)
    if n_f < 3 or n_m < 3:
        print(f'{label}: too few subjects for the sex comparison (F: n = {n_f}, M: n = {n_m}).')
        return None

    u, p = stats.mannwhitneyu(values_f, values_m, alternative='two-sided')
    r_rb = 2 * u / (n_f * n_m) - 1

    def describe(v):
        # Mean ± SD (sample SD, ddof=1), median [IQR] and range [min, max]
        q1, med, q3 = np.percentile(v, [25, 50, 75])
        return (f'mean {v.mean():.2f} ± {v.std(ddof=1):.2f} {unit}, median {med:.2f} [IQR {q1:.2f}, {q3:.2f}] {unit}, '
                f'range [{v.min():.2f}, {v.max():.2f}] {unit}')

    # Both sexes together
    values_all = pd.concat([values_f, values_m])

    print(f'{label}:\n'
          f'    Total (n = {len(values_all)}): {describe(values_all)}\n'
          f'    F (n = {n_f}): {describe(values_f)}\n'
          f'    M (n = {n_m}): {describe(values_m)}\n'
          f'    Mann-Whitney U = {u:.1f}, {format_p(p)}, rank-biserial r = {r_rb:.2f}')
    return {'label': label, 'n_total': len(values_all), 'n_F': n_f, 'n_M': n_m,
            'mean_total': values_all.mean(), 'std_total': values_all.std(ddof=1),
            'min_total': values_all.min(), 'max_total': values_all.max(),
            'mean_F': values_f.mean(), 'std_F': values_f.std(ddof=1),
            'min_F': values_f.min(), 'max_F': values_f.max(),
            'mean_M': values_m.mean(), 'std_M': values_m.std(ddof=1),
            'min_M': values_m.min(), 'max_M': values_m.max(),
            'median_F': np.median(values_f), 'median_M': np.median(values_m),
            'U': u, 'p': p, 'r_rank_biserial': r_rb}


def load_participants(fname_participants):
    """
    Load participants.tsv with unified columns participant_id, sex ('F'/'M'/NaN) and height_cm (only needed for
    tables without sex or height).
    """
    df = pd.read_csv(fname_participants, sep='\t')
    height_col = next((col for col in HEIGHT_COLUMNS if col in df.columns), None)
    if height_col is None:
        raise ValueError(f'No height column ({HEIGHT_COLUMNS}) in {fname_participants}.')
    df[HEIGHT_COL] = pd.to_numeric(df[height_col], errors='coerce')
    if df[HEIGHT_COL].notna().any() and df[HEIGHT_COL].median() < 3:   # meters -> cm
        df[HEIGHT_COL] = df[HEIGHT_COL] * 100
    df['sex'] = normalize_sex(df['sex']) if 'sex' in df.columns else np.nan
    return df[['participant_id', 'sex', HEIGHT_COL]].drop_duplicates(subset='participant_id')


def filter_session(df, session, fname):
    """
    Keep only the rows of `session` if the table has session values; tables without a session column or with an
    empty one are returned unchanged. `session='all'` keeps all sessions.
    """
    if session == 'all' or 'session' not in df.columns or df['session'].isna().all():
        return df
    sessions = df['session'].astype(str).str.strip()
    keep = sessions == session
    if not keep.any():
        print(f'WARNING: {os.path.basename(fname)} has no rows of {session} (sessions: '
              f'{sorted(sessions.unique())}); none of its rows are used.')
    elif (~keep).any():
        print(f'INFO: {os.path.basename(fname)}: kept {int(keep.sum())} row(s) of {session}, dropped '
              f'{int((~keep).sum())} row(s) of other sessions ({sorted(sessions[~keep].unique())}).')
    return df[keep].reset_index(drop=True)


def load_table(fname, fname_participants=None, session='ses-A'):
    """
    Load one C2-C8 distance table and bring it to the columns used in this script: 'subject', 'dataset', 'sex',
    HEIGHT_COL, the distance column(s), 'distance_type', 'method', 'reference' and 'source_table'. Missing information
    is taken from the table itself, its file name (e.g. '_ref_c2', '_method_PAM50', 'total_distance') or, for sex and
    height, from `fname_participants`.
    :param fname: path to the CSV/TSV table
    :param fname_participants: participants.tsv used to fill missing sex/height, or None
    :param session: session to keep (e.g. 'ses-A') or 'all'
    :return: dataframe
    """
    df = read_table(fname)
    base = os.path.basename(fname)
    if 'subject' not in df.columns:
        raise ValueError(f'No "subject" column in {fname} (detected separator {detect_separator(fname)!r}).')
    df['subject'] = df['subject'].astype(str).str.strip()

    # Final tables: the centerline length is the total C2-C8 distance
    total_col = DISTANCE_COL['total']
    if total_col not in df.columns and FINAL_TABLE_LENGTH_COL in df.columns:
        df[total_col] = pd.to_numeric(df[FINAL_TABLE_LENGTH_COL], errors='coerce')
        df['distance_type'] = 'total'
        if 'method' not in df.columns:
            df['method'] = 'centerline'
        print(f'INFO: {base}: {FINAL_TABLE_LENGTH_COL} used as the total C2-C8 distance.')
    available = [name for name, col in DISTANCE_COL.items() if col in df.columns]
    if not available:
        raise ValueError(f'{fname} has no distance column ({list(DISTANCE_COL.values()) + [FINAL_TABLE_LENGTH_COL]}).')

    # Distance type, method and reference: from the table, otherwise from the file name
    if 'distance_type' not in df.columns:
        df['distance_type'] = 'midpoint' if 'midpoints_distance' in base else 'total' if 'total_distance' in base \
            else available[0] if len(available) == 1 else np.nan
    if 'method' not in df.columns:
        df['method'] = 'rootlets' if '_rootlets' in base else 'PAM50' if '_PAM50' in base else 'unknown'
    if 'reference' not in df.columns:
        df['reference'] = 'c2' if '_ref_c2' in base else 'pmj' if '_ref_pmj' in base else 'none'

    # Dataset: from the table, otherwise the folder of participants.tsv or the file name
    if 'dataset' not in df.columns:
        df['dataset'] = os.path.basename(os.path.dirname(os.path.abspath(fname_participants))) \
            if fname_participants else os.path.splitext(base)[0]
        print(f'WARNING: no "dataset" column in {base}; using "{df["dataset"].iloc[0]}".')
    df['dataset'] = df['dataset'].astype(str).str.strip()

    # Sex and height; missing values filled from participants.tsv
    df['sex'] = normalize_sex(df['sex']) if 'sex' in df.columns else np.nan
    df[HEIGHT_COL] = pd.to_numeric(df[HEIGHT_COL], errors='coerce') if HEIGHT_COL in df.columns else np.nan
    if fname_participants:
        participants = load_participants(fname_participants).set_index('participant_id')
        df['sex'] = df['sex'].fillna(df['subject'].map(participants['sex']))
        df[HEIGHT_COL] = df[HEIGHT_COL].fillna(df['subject'].map(participants[HEIGHT_COL]))
        not_found = sorted(set(df['subject']) - set(participants.index))
        if not_found:
            print(f'WARNING: {len(not_found)} subject(s) of {base} not found in {fname_participants}: {not_found}')

    df = filter_session(df, session, fname)
    df['source_table'] = base
    print(f'Loaded {fname}: {len(df)} row(s), datasets: {", ".join(df["dataset"].unique())}')
    return df


def load_tables(fnames, fnames_participants, session='ses-A'):
    """
    Load and combine the C2-C8 distance tables. Rows present in more than one table (same dataset/subject/session)
    are kept only once (first table wins).
    :param fnames: list of paths to the tables
    :param fnames_participants: list of participants.tsv paths (or None), same length as `fnames`
    :param session: session to keep (e.g. 'ses-A') or 'all'
    :return: combined dataframe
    """
    df = pd.concat([load_table(fname, fname_p, session) for fname, fname_p in zip(fnames, fnames_participants)],
                   ignore_index=True)
    if 'session' not in df.columns:
        df['session'] = np.nan
    key = df['dataset'] + '/' + df['subject'] + '/' + df['session'].fillna('').astype(str)
    duplicated = key.duplicated(keep='first') & (df['source_table'] != df.groupby(key)['source_table']
                                                 .transform('first'))
    if duplicated.any():
        print(f'WARNING: {int(duplicated.sum())} row(s) appear in more than one table and are kept only once '
              f'(first table wins): {key[duplicated].unique().tolist()}')
        df = df[~duplicated].reset_index(drop=True)
    return df


def load_pmj_to_conus(fname, conus_col=None):
    """
    Load one PMJ-to-conus CSV file (pmj_to_conus_distance_<dataset>.csv) and return one row per subject with the
    PMJ-to-conus length in cm (CONUS_COL).
    :param fname: path to the CSV file
    :param conus_col: name of the distance column; if None, detected automatically (the only numeric column, or the
    numeric column containing 'conus' or 'distance' in its name)
    :return: dataframe with columns 'subject', CONUS_COL (and 'dataset' if present in the file)
    """
    df = read_table(fname)
    if 'subject' not in df.columns:
        raise ValueError(f'No "subject" column in {fname}.')
    df['subject'] = df['subject'].astype(str).str.strip()

    if conus_col is None:
        excluded = {'subject', 'dataset', HEIGHT_COL, 'age'}
        numeric_cols = [col for col in df.select_dtypes(include='number').columns if col not in excluded]
        candidates = [col for col in numeric_cols if 'conus' in col.lower()] or \
                     [col for col in numeric_cols if 'distance' in col.lower()] or numeric_cols
        if len(candidates) != 1:
            raise ValueError(f'Could not detect the PMJ-to-conus distance column in {fname} (numeric columns: '
                             f'{numeric_cols}); set it with -conus-col.')
        col = candidates[0]
    elif conus_col not in df.columns:
        raise ValueError(f'Column "{conus_col}" not found in {fname} (columns: {list(df.columns)}).')
    else:
        col = conus_col
    print(f'{os.path.basename(fname)}: PMJ-to-conus distance column: {col}')

    df[CONUS_COL] = pd.to_numeric(df[col], errors='coerce')
    # Values in mm (column ending with '_mm', or typical cord length > 100) are converted to cm
    if col.endswith('_mm') or (df[CONUS_COL].notna().any() and df[CONUS_COL].median() > 100):
        print(f'INFO: {os.path.basename(fname)}: PMJ-to-conus distance looks like mm; converting to cm.')
        df[CONUS_COL] = df[CONUS_COL] / 10
    keys = ['dataset', 'subject'] if 'dataset' in df.columns else ['subject']
    return df[keys + [CONUS_COL]]


def load_pmj_to_conus_tables(fnames, conus_col=None):
    """
    Load and combine one or more PMJ-to-conus CSV files; subjects with more than one value get their mean.
    :return: dataframe with one row per (dataset,) subject and CONUS_COL
    """
    list_df = [load_pmj_to_conus(fname, conus_col) for fname in fnames]
    keys = ['dataset', 'subject'] if all('dataset' in df.columns for df in list_df) else ['subject']
    df = pd.concat([d[keys + [CONUS_COL]] for d in list_df], ignore_index=True)
    duplicated = df.loc[df.duplicated(subset=keys), 'subject'].unique().tolist()
    if duplicated:
        print(f'WARNING: more than one PMJ-to-conus value for subject(s) {duplicated}; using their mean.')
    return df.groupby(keys, as_index=False)[CONUS_COL].mean()


def join_labels(values):
    """
    Unique non-empty values in their order of appearance, joined with '+' (safe for file names).
    """
    labels = [str(v).strip().replace(' ', '-').replace('/', '-') for v in dict.fromkeys(values)
              if pd.notna(v) and str(v).strip() not in ('', 'none', 'unknown')]
    return '+'.join(labels) if labels else 'none'


def main():
    parser = argparse.ArgumentParser(description='Plot the correlation between the C2-C8 distance and subject height '
                                                 '(and optionally the PMJ-to-conus length vs height and vs C2-C8 '
                                                 'distance) for one or more datasets, combined from one or more '
                                                 'tables.')
    parser.add_argument('-i', required=True, nargs='+',
                        help='One or more CSV tables with the C2-C8 distance per subject (e.g. one per dataset, '
                             'generated by compute_cervical_distance.py, or final tables). They are combined into one '
                             'analysis.')
    parser.add_argument('-participants', nargs='+', default=None,
                        help='participants.tsv with the subject height and sex, for tables without these columns: '
                             'one file for all tables, or one per table (same order as -i; "none" for a table that '
                             'does not need one).')
    parser.add_argument('-distance', choices=['auto', 'midpoint', 'total'], default='auto',
                        help='Distance to use. "auto" takes it from the tables (distance_type column or file name). '
                             'Default: auto')
    parser.add_argument('-session', default='ses-A',
                        help='For tables with a "session" column, keep only the rows of this session. Use "all" to '
                             'keep all sessions. Default: ses-A')
    parser.add_argument('-pmj-to-conus', nargs='+', default=None,
                        help='One or more PMJ-to-conus CSV files (pmj_to_conus_distance_<dataset>.csv) generated by '
                             'compute_cervical_distance.py -analyse-pmj-to-conus. If given, the PMJ-to-conus length is '
                             'correlated with height and with the C2-C8 distance.')
    parser.add_argument('-conus-col', default=None,
                        help='Name of the distance column in the -pmj-to-conus files. Default: detected automatically.')
    parser.add_argument('-output-folder', default=os.getcwd() + "/figures-and-dataframes",
                        help='Path to the output folder where the figure will be saved. '
                             'Default: current working directory.')
    args = parser.parse_args()
    os.makedirs(args.output_folder, exist_ok=True)

    # Pair each table with its participants.tsv (or None)
    fnames = [os.path.abspath(os.path.expanduser(fname)) for fname in args.i]
    if args.participants is None:
        fnames_participants = [None] * len(fnames)
    else:
        participants = [None if p.lower() == 'none' else os.path.expanduser(p) for p in args.participants]
        if len(participants) == 1:
            fnames_participants = participants * len(fnames)
        elif len(participants) == len(fnames):
            fnames_participants = participants
        else:
            parser.error(f'-participants needs 1 file or one per -i table ({len(fnames)}), got {len(participants)}.')
    for fname in fnames:
        if not os.path.isfile(fname):
            parser.error(f'{fname} does not exist.')

    # Load and combine the tables
    try:
        df = load_tables(fnames, fnames_participants, args.session)
    except ValueError as err:
        parser.error(str(err))

    # Distance type: -distance, otherwise the (single) type of the tables
    if args.distance != 'auto':
        distance = args.distance
    else:
        types = df['distance_type'].dropna().unique()
        if len(types) != 1:
            parser.error(f'The tables contain distance types {list(types)}; pass -distance midpoint or total.')
        distance = types[0]
    dist_col = DISTANCE_COL[distance]
    if dist_col not in df.columns:
        parser.error(f'None of the tables has a {dist_col} column (distance "{distance}").')
    no_distance = df[dist_col].isna()
    if no_distance.any():
        print(f'WARNING: {int(no_distance.sum())} row(s) without {dist_col} are not used: '
              f'{df.loc[no_distance, "subject"].unique().tolist()}')
        df = df[~no_distance].reset_index(drop=True)

    # Keep only subjects with height and sex available (needed for the correlation with height and sex comparison)
    missing = df[HEIGHT_COL].isna() | df['sex'].isna()
    if missing.any():
        print('WARNING: rows without height or sex are excluded:')
        for dataset, df_ds in df[missing].groupby('dataset', sort=False):
            print(f'    {dataset}: {len(df_ds)} row(s) (missing height: {int(df_ds[HEIGHT_COL].isna().sum())}, '
                  f'missing sex: {int(df_ds["sex"].isna().sum())})')
        df = df[~missing].reset_index(drop=True)
    if df.empty:
        parser.error('No subjects with the C2-C8 distance, height and sex left.')
    df[C2C8_COL] = df[dist_col] / 10          # convert mm to cm

    # Add the PMJ-to-conus length (cm), matched on dataset and subject
    if args.pmj_to_conus:
        try:
            df_conus = load_pmj_to_conus_tables([os.path.expanduser(f) for f in args.pmj_to_conus], args.conus_col)
        except ValueError as err:
            parser.error(str(err))
        keys = ['dataset', 'subject'] if 'dataset' in df_conus.columns else ['subject']
        df = df.drop(columns=[CONUS_COL], errors='ignore').merge(df_conus, on=keys, how='left')
        no_conus = (df.loc[df[CONUS_COL].isna(), 'dataset'] + '/' + df.loc[df[CONUS_COL].isna(), 'subject']).tolist()
        if no_conus:
            print(f'WARNING: {len(no_conus)} subject(s) without a PMJ-to-conus value (excluded from the PMJ-to-conus '
                  f'analyses): {no_conus}')

    # Datasets in the fixed order of DATASET_MARKERS (raises if a dataset has no marker in visualisation_utils.py)
    datasets = list(get_dataset_markers(df['dataset'].unique()))

    # Labels for the axes and the figure names
    c2c8_label = 'Length top C2 – bottom C8 [cm]' if distance == 'total' else 'Length midpoint C2 – midpoint C8 [cm]'
    conus_label = 'Length PMJ – conus [cm]'
    distance_name = 'total' if distance == 'total' else 'midpoints'
    reference_name = join_labels(df['reference'].str.upper())
    method_name = join_labels(df['method'])
    datasets_name = join_labels(datasets)
    conus_datasets_name = join_labels([ds for ds in datasets if args.pmj_to_conus and
                                       df.loc[df['dataset'] == ds, CONUS_COL].notna().any()])

    # Analyses: (x column, y column, title, x label, y label, figure name)
    analyses = [(HEIGHT_COL, C2C8_COL, 'height vs C2-C8 distance', 'Height [cm]', c2c8_label,
                 f'figure_correlation_cervical_{distance_name}_{reference_name}_distance_2-8_height_{method_name}'
                 f'_datasets_{datasets_name}.png')]
    if args.pmj_to_conus:
        analyses += [
            (HEIGHT_COL, CONUS_COL, 'height vs PMJ-to-conus length', 'Height [cm]', conus_label,
             f'figure_correlation_pmj_to_conus_length_height_datasets_{conus_datasets_name}.png'),
            (C2C8_COL, CONUS_COL, 'C2-C8 distance vs PMJ-to-conus length', c2c8_label, conus_label,
             f'figure_correlation_pmj_to_conus_length_cervical_{distance_name}_{reference_name}_distance_2-8_'
             f'{method_name}_datasets_{conus_datasets_name}.png'),
        ]

    # Subjects used per dataset (C2-C8 analysis)
    print(f'\n=== Subjects used (C2-C8 distance, {len(fnames)} table(s)) ===')
    for dataset in datasets:
        df_ds = df[df['dataset'] == dataset]
        print(f"{dataset}: {len(df_ds)} subjects ({(df_ds['sex'] == 'F').sum()} females, "
              f"{(df_ds['sex'] == 'M').sum()} males)")
    print(f"TOTAL: {len(df)} subjects ({(df['sex'] == 'F').sum()} females, {(df['sex'] == 'M').sum()} males)")

    # Spearman correlation (rank-based, does not assume normality and is robust to outliers) across all subjects
    # (shown in the figures); per-dataset correlations are only printed
    for x_col, y_col, title, xlabel, ylabel, fname_fig in analyses:
        df_an = df.dropna(subset=[x_col, y_col]).reset_index(drop=True)
        if len(df_an) < 4:
            print(f'\n{title}: only {len(df_an)} subject(s); skipped.')
            continue
        correlation_analysis(df_an, x_col, y_col, title,
                             [ds for ds in datasets if (df_an['dataset'] == ds).any()])
        plot_correlation(df_an, x_col, y_col, xlabel, ylabel, os.path.join(args.output_folder, fname_fig),
                         integer_xticks=(x_col == HEIGHT_COL))

    # Male vs female comparison (Mann-Whitney U test), all subjects pooled and per dataset. Height is compared as well
    # because a sex difference in the lengths may simply reflect the height difference between males and females.
    measures = [('C2-C8 distance', C2C8_COL), ('Height', HEIGHT_COL)]
    if args.pmj_to_conus:
        measures.append(('PMJ-to-conus length', CONUS_COL))
    for measure_label, col in measures:
        print(f'\n=== Female vs male: {measure_label} ===')
        compare_sex(df[col], df['sex'], 'All')
        datasets_col = [ds for ds in datasets if df.loc[df['dataset'] == ds, col].notna().any()]
        if len(datasets_col) > 1:
            for dataset in datasets_col:
                mask = df['dataset'] == dataset
                compare_sex(df.loc[mask, col], df.loc[mask, 'sex'], dataset)
    print()

    plt.show()


