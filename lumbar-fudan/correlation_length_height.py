"""
Plot the correlation between the lumbar L1-L5 spinal cord length and subject height for the Fudan (Shanghai)
lumbar cohort.

Input:
- CSV file with the L1-L5 length per subject generated by lumbar_fudan_L1-L5_length.py
  (L1-L5_lengths.csv; columns: subject, sex, height_cm, L1-L5_length_mm).
  (default: ~/data/spinal-levels/lumbar_mri_Fudan/derivatives/L1-L5/L1-L5_lengths.csv)

Output (saved to the same folder as the input CSV):
- figure_correlation_length_L1-L5_height.png: length vs height, coloured by sex, with the Spearman correlation
  and a least-squares linear fit (visual guide) with its 95% confidence band.

Spearman correlation is used for consistency with ../lumbar-balgrist/correlation_length_height.py.

Example:
    python correlation_length_height.py
    python correlation_length_height.py -i /path/to/L1-L5_lengths.csv

Author: Elia Rochiccioli
"""

import os
import argparse
import pandas as pd

from utils import correlation_scatter

LENGTHS_CSV = os.path.expanduser('~/data/spinal-levels/lumbar_mri_Fudan/derivatives/L1-L5/L1-L5_lengths.csv')


def main():
    parser = argparse.ArgumentParser(description='Plot the correlation between the Fudan lumbar L1-L5 length and '
                                                 'subject height.')
    parser.add_argument('-i', default=LENGTHS_CSV,
                        help=f'CSV file with the L1-L5 length per subject generated by '
                             f'lumbar_fudan_L1-L5_length.py. Default: {LENGTHS_CSV}')
    args = parser.parse_args()
    out_dir = os.path.dirname(os.path.abspath(args.i))

    df = pd.read_csv(args.i)
    df['sex'] = df['sex'].astype(str).str.upper()
    df = df.rename(columns={'height_cm': 'height'})
    df['L1-L5_length_cm'] = df['L1-L5_length_mm'] / 10   # plot in cm

    res = correlation_scatter(
        df, 'height', 'L1-L5_length_cm', 'Height [cm]', 'Lumbar cord L1–L5 length [cm]',
        'Lumbar spinal cord L1–L5 length vs height (Fudan)',
        os.path.join(out_dir, 'figure_correlation_length_L1-L5_height.png'))
    print(f"L1-L5 length vs height: Spearman rho = {res['rho']:.2f}, p = {res['p']:.3f}, "
          f"95% CI [{res['ci'][0]:.2f}, {res['ci'][1]:.2f}], n = {res['n']}")


if __name__ == '__main__':
    main()
