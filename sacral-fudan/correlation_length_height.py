"""
Plot the correlation between the sacral spinal cord length (top of S1 to the conus) and subject height for the
Fudan (Shanghai) lumbar cohort, using the shared correlation figure (visualisation_utils.plot_correlation) so the
figure matches the cervical and lumbar-combined panels (sex by color, dataset by marker, linear fit + 95% CI band,
Spearman rho [95% CI] in the upper-left corner, shared legend above the plot).

Input:
- CSV file with the sacral length per subject generated by fundan_sacral_length.py
  (fundan_sacral_length.csv; columns: subject, sex, height_cm, length_S1-conus_centerline_mm, ...).

Output (saved to the same folder as the input CSV):
- figure_correlation_sacral_length_S1-conus_height.png

Example:
    python correlation_length_height.py -i fundan_sacral_length.csv

Author: Elia Rochiccioli
"""

import os
import sys
import argparse
import pandas as pd
from scipy import stats

# Shared plotting conditions and correlation helpers (visualisation_utils.py at the repo root)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from visualisation_utils import plot_correlation, spearman_ci   # noqa: E402

DATASET = 'Fudan'   # fixed marker in visualisation_utils.DATASET_MARKERS (diamond)
LENGTHS_CSV = os.path.expanduser('~/Desktop/fundan_dataset/sacral_length/fundan_sacral_length.csv')


def main():
    parser = argparse.ArgumentParser(description='Plot the correlation between the Fudan sacral S1-conus length '
                                                 'and subject height.')
    parser.add_argument('-i', default=LENGTHS_CSV,
                        help=f'CSV file with the sacral length per subject generated by fundan_sacral_length.py. '
                             f'Default: {LENGTHS_CSV}')
    parser.add_argument('-panel-letter', default='none',
                        help='Panel letter in the upper-left corner (e.g. "C"); "none" disables it. Default: none')
    args = parser.parse_args()
    out_dir = os.path.dirname(os.path.abspath(args.i))
    panel_letter = None if args.panel_letter.strip().lower() in ('', 'none') else args.panel_letter

    df = pd.read_csv(args.i)
    df['sex'] = df['sex'].astype(str).str.upper()
    df = df.rename(columns={'height_cm': 'height'})
    df['dataset'] = DATASET
    df['sacral_length_cm'] = df['length_S1-conus_centerline_mm'] / 10   # plot in cm
    df = df.dropna(subset=['sacral_length_cm', 'height', 'sex'])

    rho, p = stats.spearmanr(df['height'], df['sacral_length_cm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    print(f'{DATASET}: n = {len(df)}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')

    plot_correlation(df, 'height', 'sacral_length_cm', 'Height [cm]', 'Sacral cord length S1 to conus tip [cm]',
                     os.path.join(out_dir, 'figure_correlation_sacral_length_S1-conus_height.png'),
                     integer_xticks=True, panel_letter=panel_letter)


if __name__ == '__main__':
    main()
