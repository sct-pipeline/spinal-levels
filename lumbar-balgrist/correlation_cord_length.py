"""
Plot the correlation between the whole spinal cord length (PMJ to conus) and subject height, and (optionally)
with the lumbar L1-L5 length.

Input:
- CSV file with the cord length per subject generated by compute_cord_length.py
  (cord_length.csv; columns: subject, cord_length_mm, and optionally sex and height).
  (default: ~/data/spinal-levels/lumbar_rootlets_Balgrist/results_and_figures/cord_length.csv)
- Optional CSV file with the lumbar L1-L5 length generated by lumbar_length_along_centerline.py
  (lumbar_length_L1-L5_centerline.csv). If given, two extra figures are produced: lumbar length vs height and
  cord length vs lumbar length.
- Excel file with the subject sex and height, used only if the cord-length CSV has no 'sex' and 'height' columns
  (default: the participants Excel (see utils.PARTICIPANTS_XLSX)).

Output (saved to the same folder as the input CSV):
- figure_correlation_cord_length_height.png
- figure_correlation_lumbar_length_height.png       (only if -lumbar is given)
- figure_correlation_cord_length_lumbar_length.png  (only if -lumbar is given)

Spearman correlation is used for consistency with correlation_length_height.py; it does not
assume normality and is robust to outliers, which matters for a small sample.

Example:
    python correlation_cord_length.py
    python correlation_cord_length.py -lumbar ~/data/spinal-levels/lumbar_rootlets_Balgrist/results_and_figures/lumbar_length_L1-L5_centerline.csv

Author: Elia Rochiccioli
"""

import os
import argparse
import pandas as pd

from utils import OUTPUT_DIR, PARTICIPANTS_XLSX, add_sex_height, correlation_scatter

CORD_CSV = os.path.join(OUTPUT_DIR, 'cord_length.csv')


def main():
    parser = argparse.ArgumentParser(description='Plot the correlation between the whole spinal cord length '
                                                 '(PMJ to conus) and subject height (and lumbar L1-L5 length).')
    parser.add_argument('-i', default=CORD_CSV,
                        help=f'CSV file with the cord length per subject generated by compute_cord_length.py. '
                             f'Default: {CORD_CSV}')
    parser.add_argument('-lumbar', default=None,
                        help='Optional CSV file with the lumbar L1-L5 length per subject generated by '
                             'lumbar_length_along_centerline.py. If given, the lumbar vs height '
                             'and cord vs lumbar figures are also produced.')
    parser.add_argument('-xlsx', default=PARTICIPANTS_XLSX,
                        help=f'Excel file with the subject sex and height, used only if the cord-length CSV has no '
                             f'sex and height columns. Default: {PARTICIPANTS_XLSX}')
    args = parser.parse_args()
    out_dir = os.path.dirname(os.path.abspath(args.i))

    # Load the cord length; add sex and height from the Excel file if not already in the CSV
    df = pd.read_csv(args.i)
    if not {'sex', 'height'}.issubset(df.columns):
        df = add_sex_height(df, args.xlsx)
    df['cord_length_cm'] = df['cord_length_mm'] / 10   # plot in cm

    # Cord length vs height
    res = correlation_scatter(
        df, 'height', 'cord_length_cm', 'Height [cm]', 'Spinal cord length PMJ–conus [cm]',
        'Spinal cord length (PMJ–conus) vs height',
        os.path.join(out_dir, 'figure_correlation_cord_length_height.png'))
    print(f"cord length vs height: Spearman rho = {res['rho']:.2f}, p = {res['p']:.3f}, n = {res['n']}")

    if args.lumbar:
        # Merge the lumbar L1-L5 length (column 'length_L1-L5_centerline_mm')
        lum = pd.read_csv(args.lumbar)
        length_col = [c for c in lum.columns if c.startswith('length_')][0]
        lum = lum.rename(columns={length_col: 'lumbar_length_mm'})
        df = df.merge(lum[['subject', 'lumbar_length_mm']], on='subject', how='left')
        df['lumbar_length_cm'] = df['lumbar_length_mm'] / 10

        res = correlation_scatter(
            df, 'height', 'lumbar_length_cm', 'Height [cm]', 'Lumbar cord L1–L5 length [cm]',
            'Lumbar spinal cord L1–L5 length vs height',
            os.path.join(out_dir, 'figure_correlation_lumbar_length_height.png'))
        print(f"lumbar length vs height: Spearman rho = {res['rho']:.2f}, p = {res['p']:.3f}, n = {res['n']}")

        res = correlation_scatter(
            df, 'lumbar_length_cm', 'cord_length_cm', 'Lumbar cord L1–L5 length [cm]',
            'Spinal cord length PMJ–conus [cm]', 'Spinal cord length (PMJ–conus) vs L1–L5 length',
            os.path.join(out_dir, 'figure_correlation_cord_length_lumbar_length.png'))
        print(f"cord length vs lumbar length: Spearman rho = {res['rho']:.2f}, p = {res['p']:.3f}, n = {res['n']}")


if __name__ == '__main__':
    main()
