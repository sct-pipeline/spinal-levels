"""
This script compares the distance between the C2 and C8 spinal levels estimated by two methods (rootlets vs PAM50)
using a paired statistical test.

Input: the per-subject CSV files generated by 'spinal_levels_distance.py' (one file per method), i.e.:
    spinal_levels_{total|midpoints}_distance_{FIRST}-{LAST}_ref_{reference}_method_rootlets.csv
    spinal_levels_{total|midpoints}_distance_{FIRST}-{LAST}_ref_{reference}_method_PAM50.csv

Steps:
1. Pair the two methods by subject (only subjects with a valid distance for both methods are kept).
2. Test the normality of the paired differences (rootlets - PAM50) using the Shapiro-Wilk test.
3. If the differences are normal (p >= alpha), use the paired t-test; otherwise, use the Wilcoxon signed-rank test.
   Both tests are reported; the selected one is marked in the output.

Output (saved to the output folder):
- CSV file with the paired per-subject values and differences
- CSV file with the statistics (descriptive statistics, normality test, paired tests)
- Figure with (A) a paired plot of both methods (one line per subject) and (B) a Bland-Altman plot
  (difference vs mean of both methods, with the bias and the 95% limits of agreement)

Bland-Altman limits of agreement follow the normality of the differences (same decision as the paired test):
- normal differences: parametric, bias = mean, limits = mean ± 1.96 SD
- non-normal differences: non-parametric, bias = median, limits = 2.5th and 97.5th percentiles
  (Bland & Altman, 1999, Stat Methods Med Res).
"""

import os
import argparse

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats


FONT_SIZE = 14

# Levels used for the distance computation: C2 and C8 (must match spinal_levels_distance.py)
FIRST_LEVEL = 2
LAST_LEVEL = 8

# Methods for spinal level estimation
METHODS = ['rootlets', 'PAM50']

# Column with the per-subject distance and file-name prefix for each distance type
DISTANCE_COL = {'midpoint': 'midpoints_distance_mm', 'total': 'total_distance_mm'}
DISTANCE_FNAME = {'midpoint': 'midpoints', 'total': 'total'}

# Colors: dark = rootlets, light = PAM50
METHOD_COLORS = {'rootlets': '#1f4e9c', 'PAM50': '#9ec5f0'}


def get_parser():
    """
    Function to parse command line arguments.
    :return: command line arguments
    """
    parser = argparse.ArgumentParser(description='Compare the C2-C8 distance between rootlets and PAM50 using a '
                                                 'paired test (normality of the differences is tested first).',
                                     prog=os.path.basename(__file__).strip('.py'))
    parser.add_argument('-i', default=os.getcwd() + '/figures-and-dataframes',
                        help='Path to the folder with the per-method distance CSV files generated by '
                             'spinal_levels_distance.py. Default: ./figures-and-dataframes')
    parser.add_argument('-reference', choices=['pmj', 'c2'], default='c2',
                        help='Reference point used for distance computation. Default: c2')
    parser.add_argument('-distance', choices=['midpoint', 'total'], default='total',
                        help='Distance to compare. Default: total')
    parser.add_argument('-alpha', type=float, default=0.05,
                        help='Significance level for the normality and paired tests. Default: 0.05')
    parser.add_argument('-output-folder', default=None,
                        help='Path to the output folder. Default: same as the input folder (-i).')
    return parser


def load_paired_data(dir_path, reference, distance):
    """
    Load the per-method CSV files and pair them by subject.
    :param dir_path: path to the folder with the per-method CSV files
    :param reference: reference point used for distance computation
    :param distance: distance to compare ('midpoint' or 'total')
    :return: dataframe with one row per subject and one column per method (in mm) and their difference
    """
    dist_col = DISTANCE_COL[distance]
    list_df = []
    for method in METHODS:
        fname = os.path.join(dir_path, f'spinal_levels_{DISTANCE_FNAME[distance]}_distance_{FIRST_LEVEL}-{LAST_LEVEL}'
                                       f'_ref_{reference}_method_{method}.csv')
        if not os.path.isfile(fname):
            raise FileNotFoundError(f'{fname} not found. Run spinal_levels_distance.py with -method both '
                                    f'(or with each method) first.')
        df = pd.read_csv(fname)[['subject', dist_col]].rename(columns={dist_col: method})
        list_df.append(df.set_index('subject'))

    df_paired = pd.concat(list_df, axis=1, join='outer')

    # Keep only subjects with a valid value for both methods
    missing = df_paired[df_paired[METHODS].isna().any(axis=1)]
    if not missing.empty:
        print(f'WARNING: {len(missing)} subject(s) excluded (missing value for at least one method): '
              f'{", ".join(missing.index)}')
    df_paired = df_paired.dropna(subset=METHODS).reset_index().rename(columns={'index': 'subject'})

    df_paired['difference'] = df_paired['rootlets'] - df_paired['PAM50']
    return df_paired


def compute_statistics(df_paired, alpha):
    """
    Test the normality of the paired differences (Shapiro-Wilk) and compute the paired t-test and the Wilcoxon
    signed-rank test. The test used for the conclusion is selected based on the normality of the differences.
    :param df_paired: dataframe returned by load_paired_data()
    :param alpha: significance level
    :return: dictionary with the statistics
    """
    x = df_paired['rootlets'].to_numpy()
    y = df_paired['PAM50'].to_numpy()
    diff = df_paired['difference'].to_numpy()
    n = len(diff)
    res = {'n_subjects': n}

    # Descriptive statistics (mm)
    for name, values in [('rootlets', x), ('PAM50', y), ('difference', diff)]:
        res[f'{name}_mean_mm'] = np.mean(values)
        res[f'{name}_std_mm'] = np.std(values, ddof=1)
        res[f'{name}_median_mm'] = np.median(values)
        res[f'{name}_iqr_mm'] = stats.iqr(values)

    # 95% confidence interval of the mean difference
    ci = stats.t.interval(0.95, n - 1, loc=np.mean(diff), scale=stats.sem(diff))
    res['difference_ci95_low_mm'], res['difference_ci95_high_mm'] = ci

    # Bland-Altman, both variants (the selected one is set below, based on the normality of the differences)
    # Parametric: bias = mean difference, 95% limits of agreement = bias ± 1.96 SD
    res['ba_parametric_bias_mm'] = np.mean(diff)
    res['ba_parametric_loa_low_mm'] = np.mean(diff) - 1.96 * np.std(diff, ddof=1)
    res['ba_parametric_loa_high_mm'] = np.mean(diff) + 1.96 * np.std(diff, ddof=1)

    # Non-parametric: bias = median difference, 95% limits of agreement = 2.5th and 97.5th percentiles
    res['ba_nonparametric_bias_mm'] = np.median(diff)
    res['ba_nonparametric_loa_low_mm'] = np.percentile(diff, 2.5)
    res['ba_nonparametric_loa_high_mm'] = np.percentile(diff, 97.5)

    # Normality (Shapiro-Wilk): the differences decide the paired test; per-method results only for information
    for name, values in [('difference', diff), ('rootlets', x), ('PAM50', y)]:
        w, p = stats.shapiro(values)
        res[f'shapiro_{name}_W'] = w
        res[f'shapiro_{name}_p'] = p
    res['differences_normal'] = bool(res['shapiro_difference_p'] >= alpha)

    # Selected Bland-Altman variant
    ba = 'parametric' if res['differences_normal'] else 'nonparametric'
    res['bland_altman_method'] = 'mean ± 1.96 SD' if ba == 'parametric' else 'median, 2.5th–97.5th percentiles'
    for key in ['bias', 'loa_low', 'loa_high']:
        res[f'bland_altman_{key}_mm'] = res[f'ba_{ba}_{key}_mm']

    # Paired t-test + effect size (Cohen's d for paired samples = mean diff / SD diff)
    t_res = stats.ttest_rel(x, y)
    res['ttest_t'] = t_res.statistic
    res['ttest_df'] = n - 1
    res['ttest_p'] = t_res.pvalue
    res['cohens_dz'] = np.mean(diff) / np.std(diff, ddof=1) if np.std(diff, ddof=1) > 0 else np.nan

    # Wilcoxon signed-rank test + effect size (matched-pairs rank-biserial correlation)
    w_res = stats.wilcoxon(x, y)
    res['wilcoxon_W'] = w_res.statistic
    res['wilcoxon_p'] = w_res.pvalue
    ranks = stats.rankdata(np.abs(diff[diff != 0]))
    r_plus, r_minus = ranks[diff[diff != 0] > 0].sum(), ranks[diff[diff != 0] < 0].sum()
    res['rank_biserial_r'] = (r_plus - r_minus) / (r_plus + r_minus) if (r_plus + r_minus) > 0 else np.nan

    # Selected test
    if res['differences_normal']:
        res['selected_test'] = 'paired t-test'
        res['selected_p'] = res['ttest_p']
    else:
        res['selected_test'] = 'Wilcoxon signed-rank test'
        res['selected_p'] = res['wilcoxon_p']
    res['significant'] = bool(res['selected_p'] < alpha)
    res['alpha'] = alpha

    return res


def print_statistics(res, distance):
    """
    Print summary of the statistics.
    :param res: dictionary returned by compute_statistics()
    :param distance: distance compared ('midpoint' or 'total')
    """
    print(f'\n=== {distance.capitalize()} distance C{FIRST_LEVEL}-C{LAST_LEVEL}: rootlets vs PAM50 '
          f'(n = {res["n_subjects"]} paired subjects) ===')
    for name in ['rootlets', 'PAM50', 'difference']:
        print(f'{name:>11}: mean = {res[f"{name}_mean_mm"]:.2f} ± {res[f"{name}_std_mm"]:.2f} mm, '
              f'median = {res[f"{name}_median_mm"]:.2f} mm (IQR {res[f"{name}_iqr_mm"]:.2f})')
    print(f'Mean difference (rootlets - PAM50) 95% CI: [{res["difference_ci95_low_mm"]:.2f}, '
          f'{res["difference_ci95_high_mm"]:.2f}] mm')

    print(f'Bland-Altman (parametric, mean ± 1.96 SD):            bias = {res["ba_parametric_bias_mm"]:.2f} mm, '
          f'LoA = [{res["ba_parametric_loa_low_mm"]:.2f}, {res["ba_parametric_loa_high_mm"]:.2f}] mm')
    print(f'Bland-Altman (non-parametric, median, 2.5–97.5 pct): bias = {res["ba_nonparametric_bias_mm"]:.2f} mm, '
          f'LoA = [{res["ba_nonparametric_loa_low_mm"]:.2f}, {res["ba_nonparametric_loa_high_mm"]:.2f}] mm')

    print('\nShapiro-Wilk normality test:')
    for name in ['difference', 'rootlets', 'PAM50']:
        print(f'{name:>11}: W = {res[f"shapiro_{name}_W"]:.3f}, p = {res[f"shapiro_{name}_p"]:.4f}')
    print(f'-> Differences are {"" if res["differences_normal"] else "NOT "}normally distributed '
          f'(alpha = {res["alpha"]}) -> {res["selected_test"]}; Bland-Altman: {res["bland_altman_method"]}')
    if not res['differences_normal'] and res['n_subjects'] < 50:
        print(f'NOTE: non-parametric limits of agreement (2.5th/97.5th percentiles) are unstable for small samples '
              f'(n = {res["n_subjects"]}); interpret with caution.')

    print('\nPaired tests:')
    print(f'Paired t-test:        t({res["ttest_df"]}) = {res["ttest_t"]:.3f}, p = {res["ttest_p"]:.4g}, '
          f'Cohen\'s dz = {res["cohens_dz"]:.2f}')
    print(f'Wilcoxon signed-rank: W = {res["wilcoxon_W"]:.1f}, p = {res["wilcoxon_p"]:.4g}, '
          f'rank-biserial r = {res["rank_biserial_r"]:.2f}')
    print(f'\n-> {res["selected_test"]}: p = {res["selected_p"]:.4g} -> '
          f'{"significant" if res["significant"] else "no significant"} difference between rootlets and PAM50.\n')


def generate_figure(df_paired, res, out_dir, reference, distance):
    """
    Generate a figure with (A) a paired plot of both methods (one line per subject) with the result of the selected
    paired test, and (B) a Bland-Altman plot (difference rootlets - PAM50 vs mean of both methods) with the bias and
    the 95% limits of agreement.
    :param df_paired: dataframe returned by load_paired_data()
    :param res: dictionary returned by compute_statistics()
    :param out_dir: path to the output folder
    :param reference: reference point used for distance computation
    :param distance: distance compared ('midpoint' or 'total')
    """
    fig, axes = plt.subplots(1, 2, figsize=(11, 5), gridspec_kw={'width_ratios': [1, 1.4]})

    # (A) Paired plot: one line per subject connecting both methods
    ax = axes[0]
    for _, row in df_paired.iterrows():
        ax.plot([0, 1], [row['rootlets'] / 10, row['PAM50'] / 10], color='lightgray', linewidth=0.8, zorder=1)
    for i, method in enumerate(METHODS):
        ax.scatter(np.full(len(df_paired), i), df_paired[method] / 10, color=METHOD_COLORS[method], s=25,
                   zorder=3, edgecolor='black', linewidth=0.3)
    ax.set_xticks([0, 1])
    ax.set_xticklabels(METHODS, fontsize=FONT_SIZE - 2)
    ax.set_xlim(-0.4, 1.4)
    ax.set_ylabel(f'{distance.capitalize()} distance C{FIRST_LEVEL}–C{LAST_LEVEL} [cm]', fontsize=FONT_SIZE - 2)
    stat_txt = (f't({res["ttest_df"]}) = {res["ttest_t"]:.2f}' if res['differences_normal']
                else f'W = {res["wilcoxon_W"]:.1f}')
    ax.set_title(f'{res["selected_test"]}\n{stat_txt}, p = {res["selected_p"]:.3g}', fontsize=FONT_SIZE - 3)

    # (B) Bland-Altman plot (mm)
    ax = axes[1]
    mean_methods = (df_paired['rootlets'] + df_paired['PAM50']) / 2
    bias = res['bland_altman_bias_mm']
    loa_low, loa_high = res['bland_altman_loa_low_mm'], res['bland_altman_loa_high_mm']
    ax.scatter(mean_methods, df_paired['difference'], color='gray', s=25, zorder=3, edgecolor='black',
               linewidth=0.3)
    ax.axhline(0, color='black', linewidth=0.6, alpha=0.4, zorder=1)
    ax.axhline(bias, color='black', linestyle='-', linewidth=1, zorder=2)
    for loa in (loa_low, loa_high):
        ax.axhline(loa, color='black', linestyle='--', linewidth=1, zorder=2)
    # Line labels on the right side of the plot
    if res['differences_normal']:
        labels = [f'+1.96 SD: {loa_high:.2f}', f'Bias (mean): {bias:.2f}', f'−1.96 SD: {loa_low:.2f}']
    else:
        labels = [f'97.5th pct: {loa_high:.2f}', f'Bias (median): {bias:.2f}', f'2.5th pct: {loa_low:.2f}']
    # Labels: upper limit and bias above their line, lower limit below its line (avoids overlap when close)
    for value, label, offset, va in zip([loa_high, bias, loa_low], labels, [3, 3, -3], ['bottom', 'bottom', 'top']):
        ax.annotate(label, xy=(1, value), xycoords=('axes fraction', 'data'), xytext=(-4, offset),
                    textcoords='offset points', ha='right', va=va, fontsize=FONT_SIZE - 5)
    # Y-limits covering the data, the limits of agreement and 0, with a margin
    y_values = np.concatenate([df_paired['difference'].to_numpy(), [loa_low, loa_high, 0]])
    margin = 0.15 * (y_values.max() - y_values.min())
    ax.set_ylim(y_values.min() - margin, y_values.max() + margin)
    ax.set_xlabel('Mean of rootlets and PAM50 [mm]', fontsize=FONT_SIZE - 2)
    ax.set_ylabel('Difference rootlets − PAM50 [mm]', fontsize=FONT_SIZE - 2)
    ax.set_title(f'Bland-Altman plot ({res["bland_altman_method"]})', fontsize=FONT_SIZE - 3)

    for ax in axes:
        ax.tick_params(labelsize=FONT_SIZE - 4)
        ax.grid(axis='y', alpha=0.2)
        ax.set_axisbelow(True)
        ax.spines['right'].set_visible(False)
        ax.spines['top'].set_visible(False)

    fig.suptitle(f'{distance.capitalize()} distance C{FIRST_LEVEL}–C{LAST_LEVEL}: rootlets vs PAM50 '
                 f'(reference: {reference.upper()}, n = {res["n_subjects"]})', fontsize=FONT_SIZE - 1)
    plt.tight_layout()

    fname_figure = os.path.join(out_dir, f'figure_stats_{distance}_distance_{FIRST_LEVEL}-{LAST_LEVEL}'
                                         f'_ref_{reference}_rootlets-vs-PAM50.png')
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')
    plt.show()


def main():
    parser = get_parser()
    args = parser.parse_args()
    dir_path = os.path.abspath(args.i)
    out_dir = os.path.abspath(args.output_folder) if args.output_folder else dir_path
    os.makedirs(out_dir, exist_ok=True)

    # Pair the methods by subject
    df_paired = load_paired_data(dir_path, args.reference, args.distance)
    fname_paired = os.path.join(out_dir, f'stats_paired_{args.distance}_distance_{FIRST_LEVEL}-{LAST_LEVEL}'
                                         f'_ref_{args.reference}_rootlets-vs-PAM50.csv')
    df_paired.to_csv(fname_paired, index=False)
    print(f'Paired values saved in {fname_paired}.')

    # Normality test + paired tests
    res = compute_statistics(df_paired, args.alpha)
    print_statistics(res, args.distance)
    fname_stats = os.path.join(out_dir, f'stats_{args.distance}_distance_{FIRST_LEVEL}-{LAST_LEVEL}'
                                        f'_ref_{args.reference}_rootlets-vs-PAM50.csv')
    pd.DataFrame([res]).T.rename(columns={0: 'value'}).to_csv(fname_stats, index_label='statistic')
    print(f'Statistics saved in {fname_stats}.')

    # Figure
    generate_figure(df_paired, res, out_dir, args.reference, args.distance)


if __name__ == '__main__':
    main()