"""
This script plots the correlation between the C2-C8 distance (midpoints or total) and subject height, for one or more
datasets combined in one figure, and compares the C2-C8 distance (and height) between males and females.

Optionally (`-pmj-to-conus`), it also plots the correlation between the PMJ-to-conus length (spinal cord length) and
  - subject height
  - the C2-C8 (cervical) length
and compares the PMJ-to-conus length between males and females.

Input:
- Combined CSV file with the C2-C8 distance per subject generated by compute_c2_c8_distance.py, e.g.
  spinal_levels_total_distance_2-8_ref_c2_method_PAM50_all_datasets.csv
  It already contains the 'dataset', 'sex' and 'height_cm' columns for all datasets (subjects with missing height or
  sex are already excluded), so no participants.tsv is needed.
- (Optional, older single-dataset CSV files without the 'height_cm' column) participants.tsv file with the subject
  height and sex via -participants
- (Optional) Combined PMJ-to-conus CSV file generated by compute_c2_c8_distance.py with -analyse-pmj-to-conus, i.e.
  pmj_to_conus_distance_all_datasets.csv, via -pmj-to-conus. The distance column is detected automatically (or set
  with -conus-col); values in mm are converted to cm. Subjects are matched on 'dataset' and 'subject'. Only subjects
  present in the C2-C8 CSV file (i.e. with sex and height) are used.

Output (saved to the output folder):
    - figure_correlation_cervical_<distance>_<reference>_distance_2-8_height_<method>.png: scatter plot (color = sex,
      marker = dataset) with a linear fit across all subjects (visual guide) and the Spearman correlation (all
      subjects pooled and per dataset)
    - With -pmj-to-conus:
        - figure_correlation_pmj_to_conus_length_height.png
        - figure_correlation_pmj_to_conus_length_cervical_<distance>_<reference>_distance_2-8_<method>.png
    - Printed to the terminal: Spearman correlations (pooled and per dataset) and male vs female comparison
      (Mann-Whitney U test) of the C2-C8 distance, height (and PMJ-to-conus length), all subjects pooled and per
      dataset

Spearman correlation is used because the distance is not normally distributed (Shapiro-Wilk test) and the sample is
small, so a single subject can strongly influence the Pearson correlation. For the same reason, males and females are
compared with the non-parametric Mann-Whitney U test (with the rank-biserial correlation as effect size) instead of
the t-test.

Example:
    python 05_correlation_cervical_length_height.py \
        -i figures-and-dataframes/spinal_levels_total_distance_2-8_ref_c2_method_PAM50_all_datasets.csv \
        -pmj-to-conus figures-and-dataframes/pmj_to_conus_distance_all_datasets.csv

Author: Jan Valosek
"""

import os
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.patches import Patch
from scipy import stats

FONT_SIZE = 14

# Unified height column (in cm) written by compute_c2_c8_distance.py
HEIGHT_COL = 'height_cm'
# Accepted height column names in participants.tsv (only used with -participants)
HEIGHT_COLUMNS = ['height (cm)', 'height_cm', 'height']

# Internal columns (in cm)
C2C8_COL = 'c2c8_cm'
CONUS_COL = 'pmj_to_conus_cm'

# Sex colors and labels (same as in compute_c2_c8_distance.py)
SEX_ORDER = ['F', 'M']
SEX_LABEL = {'F': 'Female', 'M': 'Male'}
SEX_COLOR = {'F': '#2a78d6', 'M': '#eb6834'}

# Markers per dataset (in the order the datasets appear in the CSV, i.e. the order of -i in
# compute_c2_c8_distance.py): circle, triangle, then square, diamond, ...
DATASET_MARKERS = ['o', '^', 's', 'D', 'v', 'P']


def spearman_ci(rho, n, alpha=0.05):
    """
    Confidence interval of the Spearman correlation coefficient using the Fisher z-transformation with the
    Bonett & Wright (2000) standard error, sqrt(1.06 / (n - 3)).
    """
    z = np.arctanh(rho)
    se = np.sqrt(1.06 / (n - 3))
    z_crit = stats.norm.ppf(1 - alpha / 2)
    return np.tanh(z - z_crit * se), np.tanh(z + z_crit * se)


def linear_fit_ci_band(x, y, x_fit, alpha=0.05):
    """
    Linear fit and the confidence band of the fitted mean (ordinary least squares).
    :return: y_fit, lower bound, upper bound evaluated at x_fit
    """
    n = len(x)
    slope, intercept = np.polyfit(x, y, 1)
    y_fit = slope * x_fit + intercept
    residuals = y - (slope * x + intercept)
    s = np.sqrt(np.sum(residuals ** 2) / (n - 2))   # residual standard error
    se_fit = s * np.sqrt(1 / n + (x_fit - x.mean()) ** 2 / np.sum((x - x.mean()) ** 2))
    t_crit = stats.t.ppf(1 - alpha / 2, n - 2)
    return y_fit, y_fit - t_crit * se_fit, y_fit + t_crit * se_fit


def format_p(p):
    return 'p < 0.001' if p < 0.001 else f'p = {p:.3f}'


def spearman_summary(x, y, label):
    """
    Compute the Spearman correlation with its 95% CI, print it and return a one-line string for the figure.
    """
    n = len(x)
    if n < 4:
        print(f'{label}: n = {n}, too few subjects for the Spearman correlation.')
        return f'{label}: n = {n}'
    rho, p = stats.spearmanr(x, y)
    rho_lo, rho_hi = spearman_ci(rho, n)
    print(f'{label}: n = {n}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], {format_p(p)}')
    return f'{label} (n = {n}): ρ = {rho:.2f} [{rho_lo:.2f}, {rho_hi:.2f}], {format_p(p)}'


def correlation_analysis(df, x_col, y_col, title, datasets):
    """
    Print the Shapiro-Wilk normality tests and the Spearman correlation between `x_col` and `y_col`, all subjects
    pooled and per dataset.
    :param df: dataframe with one row per subject (no missing values in x_col and y_col)
    """
    print(f'\n=== Correlation: {title} ===')
    if len(df) >= 3:
        print(f'Shapiro-Wilk normality test: {x_col} p = {stats.shapiro(df[x_col]).pvalue:.3f}, '
              f'{y_col} p = {stats.shapiro(df[y_col]).pvalue:.3f}')
    spearman_summary(df[x_col], df[y_col], 'All')
    if len(datasets) > 1:
        for dataset in datasets:
            mask = df['dataset'] == dataset
            spearman_summary(df.loc[mask, x_col], df.loc[mask, y_col], dataset)


def compare_sex(values, sex, label, unit='cm'):
    """
    Compare a measure between females and males with the two-sided Mann-Whitney U test (non-parametric, does not
    assume normality). The effect size is the rank-biserial correlation r = 2U / (n_F * n_M) - 1, where U is the
    statistic of the female group: r > 0 means females tend to have higher values, r < 0 means males do
    (|r| ~0.1 small, ~0.3 medium, ~0.5 large).
    :param values: pd.Series with the measure (e.g., C2-C8 distance in cm or height in cm)
    :param sex: pd.Series with 'F'/'M' (same index as values)
    :param label: label for the printout (e.g., 'All' or the dataset name)
    :param unit: unit of the measure for the printout
    :return: dict with the test results, or None if there are too few subjects
    """
    values_f = values[sex == 'F'].dropna()
    values_m = values[sex == 'M'].dropna()
    n_f, n_m = len(values_f), len(values_m)
    if n_f < 3 or n_m < 3:
        print(f'{label}: too few subjects for the sex comparison (F: n = {n_f}, M: n = {n_m}).')
        return None

    u, p = stats.mannwhitneyu(values_f, values_m, alternative='two-sided')
    r_rb = 2 * u / (n_f * n_m) - 1

    def describe(v):
        # Mean ± SD (sample SD, ddof=1), median [IQR] and range [min, max]
        q1, med, q3 = np.percentile(v, [25, 50, 75])
        return (f'mean {v.mean():.2f} ± {v.std(ddof=1):.2f} {unit}, median {med:.2f} [IQR {q1:.2f}, {q3:.2f}] {unit}, '
                f'range [{v.min():.2f}, {v.max():.2f}] {unit}')

    # Both sexes together
    values_all = pd.concat([values_f, values_m])

    print(f'{label}:\n'
          f'    Total (n = {len(values_all)}): {describe(values_all)}\n'
          f'    F (n = {n_f}): {describe(values_f)}\n'
          f'    M (n = {n_m}): {describe(values_m)}\n'
          f'    Mann-Whitney U = {u:.1f}, {format_p(p)}, rank-biserial r = {r_rb:.2f}')
    return {'label': label, 'n_total': len(values_all), 'n_F': n_f, 'n_M': n_m,
            'mean_total': values_all.mean(), 'std_total': values_all.std(ddof=1),
            'min_total': values_all.min(), 'max_total': values_all.max(),
            'mean_F': values_f.mean(), 'std_F': values_f.std(ddof=1),
            'min_F': values_f.min(), 'max_F': values_f.max(),
            'mean_M': values_m.mean(), 'std_M': values_m.std(ddof=1),
            'min_M': values_m.min(), 'max_M': values_m.max(),
            'median_F': np.median(values_f), 'median_M': np.median(values_m),
            'U': u, 'p': p, 'r_rank_biserial': r_rb}


def load_participants(fname_participants):
    """
    Load participants.tsv with unified columns participant_id, sex ('F'/'M'/NaN) and height_cm (only needed for older
    single-dataset CSV files without the height_cm column).
    """
    df = pd.read_csv(fname_participants, sep='\t')
    height_col = next((col for col in HEIGHT_COLUMNS if col in df.columns), None)
    if height_col is None:
        raise ValueError(f'No height column ({HEIGHT_COLUMNS}) in {fname_participants}.')
    df[HEIGHT_COL] = pd.to_numeric(df[height_col], errors='coerce')
    if df[HEIGHT_COL].notna().any() and df[HEIGHT_COL].median() < 3:   # meters -> cm
        df[HEIGHT_COL] = df[HEIGHT_COL] * 100
    sex = df['sex'].astype(str).str.strip().str.upper().str[0]
    df['sex'] = sex.where(sex.isin(SEX_ORDER))
    return df[['participant_id', 'sex', HEIGHT_COL]]


def load_pmj_to_conus(fname, conus_col=None):
    """
    Load the combined PMJ-to-conus CSV file (pmj_to_conus_distance_all_datasets.csv) and return one row per subject
    with the PMJ-to-conus length in cm (CONUS_COL).
    :param fname: path to the CSV file
    :param conus_col: name of the distance column; if None, detected automatically (the only numeric column, or the
    numeric column containing 'conus' or 'distance' in its name)
    :return: dataframe with columns 'subject', CONUS_COL (and 'dataset' if present in the file)
    """
    df = pd.read_csv(fname)
    if 'subject' not in df.columns:
        raise ValueError(f'No "subject" column in {fname}.')

    if conus_col is None:
        numeric_cols = [col for col in df.select_dtypes(include='number').columns if col not in ('subject', 'dataset')]
        candidates = [col for col in numeric_cols if 'conus' in col.lower()] or \
                     [col for col in numeric_cols if 'distance' in col.lower()] or numeric_cols
        if len(candidates) != 1:
            raise ValueError(f'Could not detect the PMJ-to-conus distance column in {fname} (numeric columns: '
                             f'{numeric_cols}); set it with -conus-col.')
        conus_col = candidates[0]
    elif conus_col not in df.columns:
        raise ValueError(f'Column "{conus_col}" not found in {fname} (columns: {list(df.columns)}).')
    print(f'PMJ-to-conus distance column: {conus_col}')

    df[CONUS_COL] = pd.to_numeric(df[conus_col], errors='coerce')
    # Values in mm (column ending with '_mm', or typical cord length > 100) are converted to cm
    if conus_col.endswith('_mm') or (df[CONUS_COL].notna().any() and df[CONUS_COL].median() > 100):
        print('INFO: PMJ-to-conus distance looks like mm; converting to cm.')
        df[CONUS_COL] = df[CONUS_COL] / 10

    keys = ['dataset', 'subject'] if 'dataset' in df.columns else ['subject']
    duplicated = df.loc[df.duplicated(subset=keys), 'subject'].unique().tolist()
    if duplicated:
        print(f'WARNING: more than one PMJ-to-conus value for subject(s) {duplicated}; using their mean.')
    return df.groupby(keys, as_index=False)[CONUS_COL].mean()


def plot_correlation(df, x_col, y_col, xlabel, ylabel, dataset_markers, fname_figure):
    """
    Scatter plot (color = sex, marker = dataset) with a linear fit across all subjects (visual guide) and its 95%
    confidence band, and the Spearman correlation across all subjects in the upper left corner.
    :param df: dataframe with one row per subject (no missing values in x_col, y_col, 'sex')
    """
    x, y = df[x_col], df[y_col]
    rho, p = stats.spearmanr(x, y)
    rho_lo, rho_hi = spearman_ci(rho, len(df))

    fig, ax = plt.subplots(figsize=(6, 5))
    for dataset, marker in dataset_markers.items():
        for sex in SEX_ORDER:
            mask = (df['dataset'] == dataset) & (df['sex'] == sex)
            if not mask.any():
                continue
            # Thin white edge so that overlapping points remain distinguishable
            ax.scatter(x[mask], y[mask], color=SEX_COLOR[sex], marker=marker, s=35, zorder=3,
                       edgecolors='white', linewidths=0.5)

    # Linear fit across all subjects (only as a visual guide) with its 95% confidence band
    x_fit = np.linspace(x.min(), x.max(), 100)
    y_fit, y_lo, y_hi = linear_fit_ci_band(x.to_numpy(), y.to_numpy(), x_fit)
    ax.fill_between(x_fit, y_lo, y_hi, color='gray', alpha=0.2, linewidth=0, zorder=1)
    ax.plot(x_fit, y_fit, color='black', linewidth=2, zorder=2)

    # Spearman correlation across all subjects in the upper left corner
    ax.text(0.03, 0.97, f'n = {len(df)}\nSpearman ρ = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], {format_p(p)}',
            transform=ax.transAxes, fontsize=FONT_SIZE - 4, va='top')

    ax.set_xlabel(xlabel, fontsize=FONT_SIZE)
    ax.set_ylabel(ylabel, fontsize=FONT_SIZE)
    ax.tick_params(axis='both', labelsize=FONT_SIZE - 2)
    ax.grid(alpha=0.2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)
    # Add headroom above the data for the correlation text
    y_min, y_max = ax.get_ylim()
    ax.set_ylim(y_min, y_max + 0.2 * (y_max - y_min))

    # Legend above the plot (upper center, outside the axes): sex colors, dataset markers and the linear fit
    handles = [Patch(color=SEX_COLOR[sex], label=f"{SEX_LABEL[sex]} (n = {(df['sex'] == sex).sum()})")
               for sex in SEX_ORDER if (df['sex'] == sex).any()]
    handles += [Line2D([], [], linestyle='', marker=marker, color='dimgray', markersize=6,
                       label=f"{dataset} (n = {(df['dataset'] == dataset).sum()})")
                for dataset, marker in dataset_markers.items() if (df['dataset'] == dataset).any()]
    handles.append(Patch(color='gray', alpha=0.3, label='Linear fit, 95% CI'))
    ax.legend(handles=handles, loc='lower center', bbox_to_anchor=(0.5, 1.0), ncol=3, frameon=False,
              fontsize=FONT_SIZE - 5, handlelength=1.2, handletextpad=0.4, columnspacing=1.2, borderaxespad=0.3)

    plt.tight_layout()
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')


def main():
    parser = argparse.ArgumentParser(description='Plot the correlation between the C2-C8 distance and subject height '
                                                 '(and optionally the PMJ-to-conus length vs height and vs C2-C8 '
                                                 'distance) for one or more datasets.')
    parser.add_argument('-i', required=True,
                        help='Combined CSV file with the C2-C8 distance per subject (all datasets) generated by '
                             'compute_c2_c8_distance.py (*_all_datasets.csv).')
    parser.add_argument('-participants', default=None,
                        help='participants.tsv with the subject height and sex. Only needed for older single-dataset '
                             'CSV files without the height_cm column.')
    parser.add_argument('-pmj-to-conus', default=None,
                        help='Combined PMJ-to-conus CSV file (pmj_to_conus_distance_all_datasets.csv) generated by '
                             'compute_c2_c8_distance.py -analyse-pmj-to-conus. If given, the PMJ-to-conus length is '
                             'correlated with height and with the C2-C8 distance.')
    parser.add_argument('-conus-col', default=None,
                        help='Name of the distance column in the -pmj-to-conus file. Default: detected automatically.')
    parser.add_argument('-output-folder', default=os.getcwd() + "/figures-and-dataframes",
                        help='Path to the output folder where the figure will be saved. '
                             'Default: current working directory.')
    args = parser.parse_args()
    os.makedirs(args.output_folder, exist_ok=True)

    # Reference, distance and method are parsed from the file name
    fname = os.path.basename(args.i)
    reference = 'C2' if '_ref_c2' in fname else 'PMJ' if '_ref_pmj' in fname else None
    distance = 'midpoints' if 'midpoints_distance' in fname else 'total' if 'total_distance' in fname else None
    method = 'rootlets' if '_rootlets' in fname else 'PAM50' if '_PAM50' in fname else None
    if None in (reference, distance, method):
        parser.error(f'Could not parse reference/distance/method from the file name {fname}.')
    dist_col = f'{distance}_distance_mm'
    c2c8_label = 'Length top C2 – bottom C8 [cm]' if distance == 'total' else 'Length midpoint C2 – midpoint C8 [cm]'
    conus_label = 'Length PMJ – conus [cm]'

    # Load the distances (and the heights/sex from participants.tsv for older CSV files)
    df = pd.read_csv(args.i)
    if HEIGHT_COL not in df.columns:
        if args.participants is None:
            parser.error(f'{fname} has no {HEIGHT_COL} column; pass -participants or use the *_all_datasets.csv '
                         f'file from compute_c2_c8_distance.py.')
        df = df.drop(columns=['sex'], errors='ignore').merge(load_participants(args.participants), left_on='subject',
                                                             right_on='participant_id')
    if 'dataset' not in df.columns:
        df['dataset'] = os.path.basename(os.path.dirname(os.path.abspath(args.participants or args.i)))

    # Keep only subjects with height and sex available
    df = df.dropna(subset=[HEIGHT_COL, 'sex']).reset_index(drop=True)
    df[C2C8_COL] = df[dist_col] / 10          # convert mm to cm

    # Add the PMJ-to-conus length (cm), matched on dataset and subject
    if args.pmj_to_conus:
        df_conus = load_pmj_to_conus(args.pmj_to_conus, args.conus_col)
        keys = ['dataset', 'subject'] if 'dataset' in df_conus.columns else ['subject']
        df = df.drop(columns=[CONUS_COL], errors='ignore').merge(df_conus, on=keys, how='left')
        no_conus = (df.loc[df[CONUS_COL].isna(), 'dataset'] + '/' + df.loc[df[CONUS_COL].isna(), 'subject']).tolist()
        if no_conus:
            print(f'WARNING: {len(no_conus)} subject(s) without a PMJ-to-conus value (excluded from the PMJ-to-conus '
                  f'analyses): {no_conus}')

    datasets = list(df['dataset'].unique())
    dataset_markers = {dataset: DATASET_MARKERS[i % len(DATASET_MARKERS)] for i, dataset in enumerate(datasets)}

    # Analyses: (x column, y column, title, x label, y label, figure name)
    analyses = [(HEIGHT_COL, C2C8_COL, 'height vs C2-C8 distance', 'Height [cm]', c2c8_label,
                 f'figure_correlation_cervical_{distance}_{reference}_distance_2-8_height_{method}.png')]
    if args.pmj_to_conus:
        analyses += [
            (HEIGHT_COL, CONUS_COL, 'height vs PMJ-to-conus length', 'Height [cm]', conus_label,
             'figure_correlation_pmj_to_conus_length_height.png'),
            (C2C8_COL, CONUS_COL, 'C2-C8 distance vs PMJ-to-conus length', c2c8_label, conus_label,
             f'figure_correlation_pmj_to_conus_length_cervical_{distance}_{reference}_distance_2-8_{method}.png'),
        ]

    # Subjects used per dataset (C2-C8 analysis)
    df_c2c8 = df.dropna(subset=[C2C8_COL])
    print('=== Subjects used (C2-C8 distance) ===')
    for dataset in datasets:
        df_ds = df_c2c8[df_c2c8['dataset'] == dataset]
        print(f"{dataset}: {len(df_ds)} subjects ({(df_ds['sex'] == 'F').sum()} females, "
              f"{(df_ds['sex'] == 'M').sum()} males)")
    print(f"TOTAL: {len(df_c2c8)} subjects ({(df_c2c8['sex'] == 'F').sum()} females, "
          f"{(df_c2c8['sex'] == 'M').sum()} males)")

    # Spearman correlation (rank-based, does not assume normality and is robust to outliers) across all subjects
    # (shown in the figures); per-dataset correlations are only printed
    for x_col, y_col, title, xlabel, ylabel, fname_fig in analyses:
        df_an = df.dropna(subset=[x_col, y_col]).reset_index(drop=True)
        if len(df_an) < 4:
            print(f'\n{title}: only {len(df_an)} subject(s); skipped.')
            continue
        correlation_analysis(df_an, x_col, y_col, title, datasets)
        plot_correlation(df_an, x_col, y_col, xlabel, ylabel, dataset_markers,
                         os.path.join(args.output_folder, fname_fig))

    # Male vs female comparison (Mann-Whitney U test), all subjects pooled and per dataset. Height is compared as well
    # because a sex difference in the lengths may simply reflect the height difference between males and females.
    measures = [('C2-C8 distance', C2C8_COL), ('Height', HEIGHT_COL)]
    if args.pmj_to_conus:
        measures.append(('PMJ-to-conus length', CONUS_COL))
    for measure_label, col in measures:
        print(f'\n=== Female vs male: {measure_label} ===')
        compare_sex(df[col], df['sex'], 'All')
        if len(datasets) > 1:
            for dataset in datasets:
                mask = df['dataset'] == dataset
                compare_sex(df.loc[mask, col], df.loc[mask, 'sex'], dataset)
    print()

    plt.show()


if __name__ == '__main__':
    main()