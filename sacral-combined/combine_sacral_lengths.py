"""
TL;DR: Plot the sacral spinal cord length (top of S1 to the conus medullaris, along the centerline) of the Balgrist
and Fudan datasets together.

Figures:
    - length per subject: all subjects (females and males together) sorted by height (`-sort-by height`, default) or
      by the sacral length (`-sort-by length`). When sorted by height, short vertical lines at the bottom mark where the
      height reaches each 10 cm (labelled "150 cm", "160 cm", ...; `-height-step` changes the step, 0 disables them).
    - correlation between the length and subject height (all subjects pooled), with a linear fit (visual guide), its
      95% confidence band, and the Spearman correlation coefficient with its 95% CI.

Sex is shown by color (Female red, Male blue) and the dataset by marker (Balgrist asterisk, Fudan diamond). Font, sex
colors, fixed marker per dataset name, marker sizes, the legend and the whole correlation figure (plot_correlation)
are shared with the other figure scripts via visualisation_utils.py, so the sacral figure matches the cervical and
lumbar panels.

Input:
    - Balgrist: CSV file generated by ../sacral-balgrist/sacral_length_along_centerline.py
    - Fudan: CSV file generated by ../sacral-fudan/fundan_sacral_length.py
    Both CSV files have the columns 'subject', 'length_S1-conus_centerline_mm', 'sex' and 'height' (or 'height_cm').
    A dataset is skipped when its file is set to an empty string (e.g. `-fudan ''`).

Output (saved to the -o folder):
    - sacral_length_S1-conus_<datasets>.csv: length, sex and height of all subjects, with the dataset
    - figure_sacral_length_S1-conus_<datasets>_sorted_by_height.png (or ..._sorted_by_sacral_length.png): length per
      subject
    - figure_correlation_sacral_length_S1-conus_<datasets>_height.png: length vs. height

Example:
    python combine_sacral_lengths.py

Author: Elia Rochiccioli (adapted from ../lumbar-combined/combine_lumbar_lengths.py by Jan Valosek).
"""

import os
import sys
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import statsmodels.formula.api as smf
from scipy import stats

# Shared plotting conditions and correlation helpers (visualisation_utils.py at the repo root)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from visualisation_utils import (LENGTH_FIGURE_FONT_SIZE, SEX_LABEL, SEX_COLOR, get_dataset_markers,  # noqa: E402
                                 scatter_points, legend_handles, add_legend_above, plot_correlation, spearman_ci,
                                 SPINAL_REGIONAL_LENGTH_FIGSIZE)

DATA_DIR = os.path.expanduser('~/Desktop')
BALGRIST_CSV = os.path.join(DATA_DIR, 'Balgrist Dataset', 'sacral_length', 'sacral_length_S1-conus_centerline.csv')
FUDAN_CSV = os.path.join(DATA_DIR, 'fundan_dataset', 'sacral_length', 'fundan_sacral_length.csv')
OUTPUT_DIR = os.path.join(DATA_DIR, 'figures_sacral_combined')

# Sexes shown in this script (subjects without sex are excluded)
SEXES = ['F', 'M']

YLABEL = 'Sacral cord length S1 to conus tip [cm]'


def load_dataset(fname, dataset):
    """
    Load the length, sex and height of one dataset.
    :param fname: CSV or XLSX file with the 'subject', 'length_S1-conus_..._mm', 'sex' and 'height' (or 'height_cm')
    columns
    :param dataset: dataset name (key of DATASET_MARKERS in visualisation_utils.py)
    :return: dataframe with 'dataset', 'subject', 'length_mm', 'sex' and 'height' columns
    """
    df = pd.read_excel(fname) if fname.endswith('.xlsx') else pd.read_csv(fname)
    df = df.rename(columns={'height_cm': 'height'})
    length_column = [c for c in df.columns if c.startswith('length_S1-conus') or c.startswith('sacral_length')][0]
    print(f'{dataset}: {len(df)} subjects, length column: {length_column}')
    df = df.rename(columns={length_column: 'length_mm'})
    df['dataset'] = dataset
    return df[['dataset', 'subject', 'length_mm', 'sex', 'height']]


def datasets_in_order(df):
    """Datasets present in `df`, in the fixed order of DATASET_MARKERS."""
    return list(get_dataset_markers(df['dataset'].unique()))


def draw_height_marks(ax, heights, step=10):
    """
    Draw a short vertical line at the bottom of the plot where the height of the (height-sorted) subjects reaches each
    multiple of `step` cm, labelled with that height (e.g. '150 cm', '160 cm', ...).
    """
    heights = np.asarray(heights, dtype=float)
    if len(heights) == 0:
        return
    transform = ax.get_xaxis_transform()
    first_mark = np.ceil(heights.min() / step) * step
    for mark in np.arange(first_mark, heights.max() + step / 2, step):
        idx = np.argmax(heights >= mark)
        if heights[idx] < mark:
            continue
        x_mark = idx + 1 - 0.5
        ax.plot([x_mark, x_mark], [0, 0.06], transform=transform, color='dimgray', linewidth=1, zorder=2,
                clip_on=False)
        ax.annotate(f'{mark:.0f} cm', xy=(x_mark, 0.02), xycoords=transform, xytext=(3, 0),
                    textcoords='offset points', ha='left', va='bottom', fontsize=LENGTH_FIGURE_FONT_SIZE - 3,
                    color='dimgray')


def datasets_suffix(df):
    """Part of the output file names with the included datasets, e.g. 'balgrist_fudan'."""
    return '_'.join(dataset.lower() for dataset in datasets_in_order(df))


def add_panel_letter(fig, letter):
    """Add a bold panel letter in the top-left corner of the figure (None or '' disables it)."""
    if not letter:
        return
    fig.text(0.01, 0.99, letter, ha='left', va='top', fontsize=LENGTH_FIGURE_FONT_SIZE + 4, fontweight='bold')


def generate_length_figure(df, dir_out, sort_by='height', height_step=10, panel_letter=None):
    """Length per subject sorted by height or by the sacral length. Sex by color, dataset by marker."""
    sort_cols = ['height', 'length_mm', 'subject'] if sort_by == 'height' else ['length_mm', 'height', 'subject']
    df = df.sort_values(sort_cols).reset_index(drop=True)
    x = np.arange(1, len(df) + 1)
    y = df['length_mm'].to_numpy() / 10  # convert mm to cm
    dataset_markers = get_dataset_markers(df['dataset'].unique())

    fig, ax = plt.subplots(figsize=SPINAL_REGIONAL_LENGTH_FIGSIZE)
    for dataset, marker in dataset_markers.items():
        for sex in SEXES:
            mask = ((df['sex'] == sex) & (df['dataset'] == dataset)).to_numpy()
            if mask.any():
                scatter_points(ax, x[mask], y[mask], color=SEX_COLOR[sex], marker=marker)

    if sort_by == 'height' and height_step > 0:
        draw_height_marks(ax, df['height'].to_numpy(), height_step)

    sort_label = 'height' if sort_by == 'height' else 'sacral length'
    ax.set_xticks([])
    ax.set_xlim(0.5, len(df) + 0.5)
    ax.set_xlabel(f'Subjects sorted by {sort_label}', fontsize=LENGTH_FIGURE_FONT_SIZE)
    ax.set_ylim(0, 6)
    ax.set_ylabel(YLABEL, fontsize=LENGTH_FIGURE_FONT_SIZE)
    ax.tick_params(axis='y', labelsize=LENGTH_FIGURE_FONT_SIZE - 2)
    ax.grid(axis='y', alpha=0.2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)
    add_legend_above(ax, legend_handles(df, dataset_markers), font_size=LENGTH_FIGURE_FONT_SIZE)
    plt.tight_layout()
    plt.tight_layout()
    add_panel_letter(fig, panel_letter)

    sort_part = 'height' if sort_by == 'height' else 'sacral_length'
    fname_figure = os.path.join(dir_out, f'figure_sacral_length_S1-conus_{datasets_suffix(df)}_sorted_by_{sort_part}.png')
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')


def print_spearman(df, name):
    """Print the Spearman correlation between the height and the length for a subset of subjects."""
    if len(df) < 4:
        print(f'{name}: n = {len(df)}, too few subjects for the Spearman correlation.')
        return
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    print(f'{name}: n = {len(df)}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')


def generate_correlation_figure(df, dir_out, panel_letter=None):
    """Length vs. height (all subjects pooled) with the shared correlation figure (plot_correlation)."""
    print_spearman(df, 'All subjects')
    for dataset in datasets_in_order(df):
        print_spearman(df[df['dataset'] == dataset], dataset)
    for sex in SEXES:
        print_spearman(df[df['sex'] == sex], SEX_LABEL[sex])

    df_plot = df.assign(length_cm=df['length_mm'] / 10)
    fname_figure = os.path.join(dir_out, f'figure_correlation_sacral_length_S1-conus_{datasets_suffix(df)}_height.png')
    plot_correlation(df_plot, 'height', 'length_cm', 'Height [cm]', YLABEL, fname_figure, integer_xticks=True,
                     panel_letter=panel_letter)


def print_summary(df):
    """Overview of the sacral length (mean +/- SD [range]) with the female vs. male comparison (Mann-Whitney U) and
    the length-height association adjusted for sex (OLS 'length_mm ~ sex + height')."""
    def describe(values, unit='mm'):
        return f'{values.mean():.1f} +/- {values.std():.1f} {unit} [{values.min():.1f}-{values.max():.1f}]'

    n_female, n_male = (df['sex'] == 'F').sum(), (df['sex'] == 'M').sum()
    female, male = df.loc[df['sex'] == 'F', 'length_mm'], df.loc[df['sex'] == 'M', 'length_mm']
    p_sex = stats.mannwhitneyu(female, male).pvalue
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    height_female, height_male = df.loc[df['sex'] == 'F', 'height'], df.loc[df['sex'] == 'M', 'height']
    p_height_sex = stats.mannwhitneyu(height_female, height_male).pvalue
    model = smf.ols('length_mm ~ sex + height', data=df).fit()
    beta_height, p_height_adj = model.params['height'], model.pvalues['height']
    beta_lo, beta_hi = model.conf_int().loc['height']

    print('\n===== Summary: sacral length S1 to conus along the centerline (mean +/- SD [range]) =====')
    print(f"All:      n = {len(df)} ({n_female} F / {n_male} M), {describe(df['length_mm'])}")
    for dataset in datasets_in_order(df):
        subset = df[df['dataset'] == dataset]
        print(f"{dataset + ':':<9} n = {len(subset)}, {describe(subset['length_mm'])}")
    print(f'Female:   n = {n_female}, {describe(female)}')
    print(f'Male:     n = {n_male}, {describe(male)}')
    print(f'Female vs. male: Mann-Whitney U p = {p_sex:.3f}')
    print(f"Height:   {describe(df['height'], unit='cm')}")
    print(f"Height female: {describe(height_female, unit='cm')}, male: {describe(height_male, unit='cm')}, "
          f"Mann-Whitney U p = {p_height_sex:.3g}")
    print(f'Length vs. height: Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')
    print(f'Length vs. height adjusted for sex (OLS length_mm ~ sex + height): beta = {beta_height:+.2f} mm/cm '
          f'[95% CI {beta_lo:+.2f}, {beta_hi:+.2f}], p = {p_height_adj:.3f}')
    print('=' * 88)


def main():
    parser = argparse.ArgumentParser(description='Combine the sacral S1-conus length of the Balgrist and Fudan '
                                                 'datasets into a per-subject figure and a correlation with height.')
    parser.add_argument('-balgrist', default=BALGRIST_CSV,
                        help=f'CSV file with the Balgrist sacral lengths. Default: {BALGRIST_CSV}')
    parser.add_argument('-fudan', default=FUDAN_CSV,
                        help=f"CSV file with the Fudan sacral lengths ('' to skip the dataset). Default: {FUDAN_CSV}")
    parser.add_argument('-sort-by', choices=['height', 'length'], default='height',
                        help='Order of the subjects on the x-axis of the length figure. Default: height')
    parser.add_argument('-height-step', type=float, default=10,
                        help='Height-mark step (cm) when sorted by height; 0 disables them. Default: 10')
    parser.add_argument('-panel-letter', default='none',
                        help='Panel letter drawn in the top-left corner (e.g. "C"); "none" disables it. Default: none')
    parser.add_argument('-o', default=OUTPUT_DIR, help=f'Output folder. Default: {OUTPUT_DIR}')
    args = parser.parse_args()
    dir_out = os.path.abspath(os.path.expanduser(args.o))
    os.makedirs(dir_out, exist_ok=True)

    files = {'Balgrist': args.balgrist, 'Fudan': args.fudan}
    files = {dataset: fname for dataset, fname in files.items() if fname}
    get_dataset_markers(files)   # fail early if a dataset has no fixed marker

    df = pd.concat([load_dataset(os.path.expanduser(fname), dataset) for dataset, fname in files.items()],
                   ignore_index=True)
    df['sex'] = df['sex'].str.upper()
    n_all = len(df)
    df = df.dropna(subset=['length_mm', 'sex', 'height']).reset_index(drop=True)
    if len(df) < n_all:
        print(f'WARNING: {n_all - len(df)} subjects without length, sex or height excluded.')

    fname_csv = os.path.join(dir_out, f'sacral_length_S1-conus_{datasets_suffix(df)}.csv')
    df.to_csv(fname_csv, index=False)
    print(f'CSV file saved in {fname_csv}.')

    panel_letter = None if args.panel_letter.strip().lower() in ('', 'none') else args.panel_letter
    generate_length_figure(df, dir_out, args.sort_by, args.height_step, panel_letter=panel_letter)
    generate_correlation_figure(df, dir_out, panel_letter=panel_letter)
    print_summary(df)


if __name__ == '__main__':
    main()
