"""
TL;DR: Plot the lumbar spinal cord length (top of L1 to bottom of L5, along the centerline) of the Balgrist, EPFL and
Fudan datasets together.

Figures:
    - length per subject: subjects stratified by sex (females, then males) and, within each sex, sorted by height
    - correlation between the length and subject height (all subjects pooled), with a linear fit (visual guide), its
      95% confidence band, and the Spearman correlation coefficient with its 95% CI

Sex is shown by color and the dataset by marker.

Input:
    - Balgrist: CSV file generated by ../lumbar-balgrist/lumbar_length_along_centerline.py
    - EPFL: CSV file generated by ../lumbar-epfl/lumbar_length_along_centerline.py
    Both CSV files have the columns 'subject', 'length_L1-L5_..._mm', 'sex' and 'height'.
    - Fudan: XLSX file with the columns 'subject', 'L1-L5_length_mm', 'sex' and 'height_cm' (and others, not used)

Output (saved to the -o folder):
    - lumbar_length_L1-L5_balgrist_epfl_fudan.csv: length, sex and height of all subjects, with the dataset
    - figure_lumbar_length_L1-L5_balgrist_epfl_fudan.png: length per subject
    - figure_correlation_lumbar_length_L1-L5_balgrist_epfl_fudan_height.png: length vs. height

Example:
    python combine_lumbar_lengths.py

Author: Jan Valosek
"""

import os
import sys
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import MaxNLocator
from scipy import stats

# Plotting style and statistics shared with the per-dataset scripts (imported from lumbar-epfl only; lumbar-balgrist
# has its own utils.py with the same name)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lumbar-epfl'))
from utils import FONT_SIZE, SEX_STYLE, spearman_ci, linear_fit_ci_band  # noqa: E402

DATA_DIR = os.path.expanduser('~/data/spinal-levels')
BALGRIST_CSV = os.path.join(DATA_DIR, 'lumbar_rootlets_Balgrist', 'results_and_figures',
                            'lumbar_length_L1-L5_centerline.csv')
EPFL_CSV = os.path.join(DATA_DIR, 'lumbar_mri_Sergio', 'results_and_figures', 'lumbar_length_L1-L5_along_centerline.csv')
FUDAN_XLSX = os.path.join(DATA_DIR, 'lumbar_fudan', 'L1-L5_lengths.xlsx')
OUTPUT_DIR = os.path.join(DATA_DIR, 'figures_lumbar_combined')

# Dataset markers (sex is shown by color, see SEX_STYLE)
DATASET_MARKER = {'Balgrist': 'o', 'EPFL': '^', 'Fudan': 's'}

YLABEL = 'Length top L1 – bottom L5 [cm]'


def load_dataset(fname, dataset):
    """
    Load the length, sex and height of one dataset.
    :param fname: CSV or XLSX file with the 'subject', 'length_L1-L5_..._mm' (or 'L1-L5_length_mm'), 'sex' and
    'height' (or 'height_cm') columns
    :param dataset: dataset name (key of DATASET_MARKER)
    :return: dataframe with 'dataset', 'subject', 'length_mm', 'sex' and 'height' columns
    """
    df = pd.read_excel(fname) if fname.endswith('.xlsx') else pd.read_csv(fname)
    df = df.rename(columns={'height_cm': 'height'})
    length_column = [c for c in df.columns if c.startswith('length_L1-L5') or c.startswith('L1-L5_length')][0]
    print(f'{dataset}: {len(df)} subjects, length column: {length_column}')
    df = df.rename(columns={length_column: 'length_mm'})
    df['dataset'] = dataset
    return df[['dataset', 'subject', 'length_mm', 'sex', 'height']]


def legend_handles(df):
    """
    Legend handles: sex (color) and dataset (marker), with the number of subjects.
    """
    handles = [Line2D([], [], color=style['color'], marker='o', linestyle='',
                      label=f"{style['label']} (n = {(df['sex'] == sex).sum()})")
               for sex, style in SEX_STYLE.items()]
    handles += [Line2D([], [], color='gray', marker=marker, linestyle='',
                       label=f"{dataset} (n = {(df['dataset'] == dataset).sum()})")
                for dataset, marker in DATASET_MARKER.items()]
    return handles


def scatter_by_sex_and_dataset(ax, df, x, y, **kwargs):
    """
    Scatter plot with the color given by sex and the marker by dataset.
    """
    for sex, style in SEX_STYLE.items():
        for dataset, marker in DATASET_MARKER.items():
            mask = ((df['sex'] == sex) & (df['dataset'] == dataset)).to_numpy()
            ax.scatter(x[mask], y[mask], color=style['color'], marker=marker, s=50, zorder=3, **kwargs)


def style_axes(ax, handles):
    """Common axes style, with the legend above the plot."""
    ax.tick_params(axis='both', labelsize=FONT_SIZE - 2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)
    ax.legend(handles=handles, loc='lower right', bbox_to_anchor=(1, 1), ncol=3, frameon=False,
              fontsize=FONT_SIZE - 5, handletextpad=0.3, columnspacing=1)


def generate_length_figure(df, dir_out):
    """
    Length per subject: subjects stratified by sex (females, then males) and, within each sex, sorted by height.
    """
    df = df.sort_values(['sex', 'height', 'subject']).reset_index(drop=True)   # 'F' before 'M'
    x = np.arange(1, len(df) + 1)
    y = df['length_mm'].to_numpy() / 10  # convert mm to cm

    fig, ax = plt.subplots(figsize=(max(6, len(df) * 0.35), 5))
    scatter_by_sex_and_dataset(ax, df, x, y)

    # Vertical line between females and males, with the group names
    n_female = (df['sex'] == 'F').sum()
    ax.axvline(n_female + 0.5, color='gray', linestyle='--', linewidth=1)
    for sex, x_center in (('F', (n_female + 1) / 2), ('M', (n_female + 1 + len(df)) / 2)):
        ax.text(x_center, 11.5, SEX_STYLE[sex]['label'], ha='center', va='top', fontsize=FONT_SIZE - 2,
                color=SEX_STYLE[sex]['color'])

    ax.set_xticks(x)
    ax.set_xticklabels(df['subject'], rotation=45, ha='right', fontsize=FONT_SIZE - 5)
    ax.set_xlim(0.5, len(df) + 0.5)
    ax.set_xlabel('Subjects stratified by sex and sorted by height', fontsize=FONT_SIZE)
    ax.set_ylim(0, 12)
    ax.set_ylabel(YLABEL, fontsize=FONT_SIZE)
    ax.grid(axis='y', alpha=0.2)
    style_axes(ax, legend_handles(df))
    ax.tick_params(axis='x', labelsize=FONT_SIZE - 5)
    plt.tight_layout()

    fname_figure = os.path.join(dir_out, 'figure_lumbar_length_L1-L5_balgrist_epfl_fudan.png')
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')


def print_spearman(df, name):
    """Print the Spearman correlation between the height and the length for a subset of subjects."""
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    print(f'{name}: n = {len(df)}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')


def generate_correlation_figure(df, dir_out):
    """
    Length vs. height (all subjects pooled), with a linear fit (visual guide) and its 95% confidence band, and the
    Spearman correlation coefficient with its 95% CI.
    """
    height = df['height'].astype(float).to_numpy()
    length = df['length_mm'].to_numpy() / 10  # convert mm to cm

    # Spearman correlation (rank-based, does not assume normality and is robust to outliers); per dataset and per sex
    # only printed
    rho, p = stats.spearmanr(height, length)
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    p_str = 'p < 0.001' if p < 0.001 else f'p = {p:.3f}'
    print_spearman(df, 'All subjects')
    for dataset in DATASET_MARKER:
        print_spearman(df[df['dataset'] == dataset], dataset)
    for sex, style in SEX_STYLE.items():
        print_spearman(df[df['sex'] == sex], style['label'])

    fig, ax = plt.subplots(figsize=(6, 5))
    scatter_by_sex_and_dataset(ax, df, height, length, edgecolors='white', linewidths=0.5)

    # Linear fit across all subjects (only as a visual guide) with its 95% confidence band
    x_fit = np.linspace(height.min(), height.max(), 100)
    y_fit, y_lo, y_hi = linear_fit_ci_band(height, length, x_fit)
    ax.fill_between(x_fit, y_lo, y_hi, color='gray', alpha=0.2, linewidth=0, zorder=1)
    ax.plot(x_fit, y_fit, color='black', linewidth=2, zorder=2)

    ax.text(0.03, 0.97, f'n = {len(df)}\nSpearman ρ = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], {p_str}',
            transform=ax.transAxes, fontsize=FONT_SIZE - 4, va='top')

    ax.set_xlabel('Height [cm]', fontsize=FONT_SIZE)
    ax.xaxis.set_major_locator(MaxNLocator(integer=True, steps=[1, 2, 5, 10]))  # integer ticks for height
    ax.set_ylabel(YLABEL, fontsize=FONT_SIZE)
    ax.grid(alpha=0.2)
    # Add headroom above the data for the correlation text
    y_min, y_max = ax.get_ylim()
    ax.set_ylim(y_min, y_max + 0.2 * (y_max - y_min))
    style_axes(ax, legend_handles(df))
    plt.tight_layout()

    fname_figure = os.path.join(dir_out, 'figure_correlation_lumbar_length_L1-L5_balgrist_epfl_fudan_height.png')
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')


def print_summary(df):
    """
    Print a short overview of the L1-L5 length (mean ± SD [range]) to copy into an abstract.
    """
    def describe(values, unit='mm'):
        return f'{values.mean():.1f} ± {values.std():.1f} {unit} [{values.min():.1f}–{values.max():.1f}]'

    n_female, n_male = (df['sex'] == 'F').sum(), (df['sex'] == 'M').sum()
    female, male = df.loc[df['sex'] == 'F', 'length_mm'], df.loc[df['sex'] == 'M', 'length_mm']
    p_sex = stats.mannwhitneyu(female, male).pvalue
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))

    print('\n===== Summary: length top L1 – bottom L5 along the centerline (mean ± SD [range]) =====')
    print(f"All:      n = {len(df)} ({n_female} F / {n_male} M), {describe(df['length_mm'])}")
    for dataset in DATASET_MARKER:
        subset = df[df['dataset'] == dataset]
        print(f"{dataset + ':':<9} n = {len(subset)}, {describe(subset['length_mm'])}")
    print(f'Female:   n = {n_female}, {describe(female)}')
    print(f'Male:     n = {n_male}, {describe(male)}')
    print(f'Female vs. male: Mann-Whitney U p = {p_sex:.3f}')
    print(f"Height:   {describe(df['height'], unit='cm')}")
    print(f'Length vs. height: Spearman ρ = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')
    print('=' * 88)

    # The same in a single sentence; the wording depends on the significance (p < 0.05)
    n_dataset = ', '.join(f"{dataset} n = {(df['dataset'] == dataset).sum()}" for dataset in DATASET_MARKER)
    sex_result = 'a significant' if p_sex < 0.05 else 'no significant'
    height_result = 'a significant' if p < 0.05 else 'no significant'
    print(f"\nIn {len(df)} participants ({n_female} F / {n_male} M; {n_dataset}), the spinal cord length from the top "
          f"of L1 to the bottom of L5 measured along the centerline was {df['length_mm'].mean():.1f} ± "
          f"{df['length_mm'].std():.1f} mm (range {df['length_mm'].min():.1f}–{df['length_mm'].max():.1f} mm), "
          f"with {sex_result} difference between females and males ({female.mean():.1f} ± {female.std():.1f} vs. "
          f"{male.mean():.1f} ± {male.std():.1f} mm, p = {p_sex:.3f}) and {height_result} correlation with body "
          f"height (Spearman ρ = {rho:.2f}, p = {p:.3f}).")


def main():
    parser = argparse.ArgumentParser(description='Combine the lumbar L1-L5 length of the Balgrist, EPFL and Fudan '
                                                 'datasets into a per-subject figure and a correlation with height.')
    parser.add_argument('-balgrist', default=BALGRIST_CSV,
                        help=f'CSV file with the Balgrist lengths. Default: {BALGRIST_CSV}')
    parser.add_argument('-epfl', default=EPFL_CSV,
                        help=f'CSV file with the EPFL lengths. Default: {EPFL_CSV}')
    parser.add_argument('-fudan', default=FUDAN_XLSX,
                        help=f'XLSX file with the Fudan lengths. Default: {FUDAN_XLSX}')
    parser.add_argument('-o', default=OUTPUT_DIR,
                        help=f'Output folder for the CSV file and the figures. Default: {OUTPUT_DIR}')
    args = parser.parse_args()
    dir_out = os.path.abspath(os.path.expanduser(args.o))
    os.makedirs(dir_out, exist_ok=True)

    df = pd.concat([load_dataset(os.path.expanduser(args.balgrist), 'Balgrist'),
                    load_dataset(os.path.expanduser(args.epfl), 'EPFL'),
                    load_dataset(os.path.expanduser(args.fudan), 'Fudan')], ignore_index=True)
    df['sex'] = df['sex'].str.upper()
    # Keep only subjects with the length, sex and height available
    n_all = len(df)
    df = df.dropna(subset=['length_mm', 'sex', 'height']).reset_index(drop=True)
    if len(df) < n_all:
        print(f'WARNING: {n_all - len(df)} subjects without length, sex or height excluded.')

    fname_csv = os.path.join(dir_out, 'lumbar_length_L1-L5_balgrist_epfl_fudan.csv')
    df.to_csv(fname_csv, index=False)
    print(f'CSV file saved in {fname_csv}.')

    generate_length_figure(df, dir_out)
    generate_correlation_figure(df, dir_out)
    print_summary(df)
    plt.show()


if __name__ == '__main__':
    main()
