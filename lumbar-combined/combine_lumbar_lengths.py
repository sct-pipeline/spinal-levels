"""
TL;DR: Plot the lumbar spinal cord length (top of L1 to bottom of L5, along the centerline) of the Balgrist, EPFL,
Fudan and NeuroRestore datasets together.

Figures:
    - length per subject: all subjects (females and males together) sorted by height (`-sort-by height`, default) or
      by the L1-L5 length (`-sort-by length`). When sorted by height, short vertical lines at the bottom mark where the
      height reaches each 10 cm (labelled "150 cm", "160 cm", ...; `-height-step` changes the step, 0 disables them)
    - correlation between the length and subject height (all subjects pooled), with a linear fit (visual guide), its
      95% confidence band, and the Spearman correlation coefficient with its 95% CI

Sex is shown by color and the dataset by marker. Font, sex colors, fixed marker per dataset name, marker sizes, the
legend and the whole correlation figure (plot_correlation) are shared with the other figure scripts via
visualisation_utils.py.

Input:
    - Balgrist: CSV file generated by ../lumbar-balgrist/lumbar_length_along_centerline.py
    - EPFL: CSV file generated by ../lumbar-epfl/lumbar_length_along_centerline.py
    Both CSV files have the columns 'subject', 'length_L1-L5_..._mm', 'sex' and 'height'.
    - Fudan: XLSX file with the columns 'subject', 'L1-L5_length_mm', 'sex' and 'height_cm' (and others, not used)
    - NeuroRestore (private, only the measurements are shared): TSV file with the columns 'sub-id', 'sex [F/M]',
      'body_height [cm]', 'L1-L5 [cm]' and 'affection' (only HEALTHY subjects are kept; patients are excluded)
    A dataset is skipped when its file is set to an empty string (e.g. `-neurorestore ''`).

Output (saved to the -o folder):
    The file names contain the included datasets, e.g. `balgrist_epfl_fudan_neurorestore`:
    - lumbar_length_L1-L5_<datasets>.csv: length, sex and height of all subjects, with the dataset
    - figure_lumbar_length_L1-L5_<datasets>_sorted_by_height.png (or ..._sorted_by_lumbar_length.png with
      `-sort-by length`): length per subject
    - figure_correlation_lumbar_length_L1-L5_<datasets>_height.png: length vs. height

Example:
    python combine_lumbar_lengths.py -sort-by length

Author: Jan Valosek
"""

import os
import sys
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats

# Shared plotting conditions and correlation helpers (visualisation_utils.py); adjust if visualisation_utils.py lives
# elsewhere in the repo
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from visualisation_utils import (FONT_SIZE, SEX_LABEL, SEX_COLOR, get_dataset_markers, scatter_points,  # noqa: E402
                                 legend_handles, add_legend_above, plot_correlation, spearman_ci,
                                 SPINAL_REGIONAL_LENGTH_FIGSIZE)

DATA_DIR = os.path.expanduser('~/data/spinal-levels')
BALGRIST_CSV = os.path.join(DATA_DIR, 'lumbar_Balgrist', 'results_and_figures',
                            'lumbar_length_L1-L5_centerline.csv')
EPFL_CSV = os.path.join(DATA_DIR, 'lumbar_epfl', 'results_and_figures', 'lumbar_length_L1-L5_along_centerline.csv')
FUDAN_XLSX = os.path.join(DATA_DIR, 'lumbar_fudan', 'L1-L5_lengths.xlsx')
NEURORESTORE_TSV = os.path.join(DATA_DIR, 'lumbar_neurorestore', 'Internal_NeuroRestore_dataset.tsv')
OUTPUT_DIR = os.path.join(DATA_DIR, 'figures_lumbar_combined')

# Sexes shown in this script (subjects without sex are excluded)
SEXES = ['F', 'M']

YLABEL = 'Length top L1 – bottom L5 [cm]'


def load_dataset(fname, dataset):
    """
    Load the length, sex and height of one dataset.
    :param fname: CSV or XLSX file with the 'subject', 'length_L1-L5_..._mm' (or 'L1-L5_length_mm'), 'sex' and
    'height' (or 'height_cm') columns, or the NeuroRestore TSV file (length in cm, healthy subjects only, see the
    module docstring)
    :param dataset: dataset name (key of DATASET_MARKERS in visualisation_utils.py)
    :return: dataframe with 'dataset', 'subject', 'length_mm', 'sex' and 'height' columns
    """
    if fname.endswith('.tsv'):
        df = pd.read_csv(fname, sep='\t')
        # Keep only healthy subjects (the dataset also includes SCI, PD, MSA-PD and PAF patients)
        n_all = len(df)
        df = df[df['affection'] == 'HEALTHY']
        print(f'{dataset}: {n_all - len(df)} patients excluded, only healthy subjects kept.')
        df = df.rename(columns={'sub-id': 'subject', 'sex [F/M]': 'sex', 'body_height [cm]': 'height'})
        df['L1-L5_length_mm'] = df.pop('L1-L5 [cm]') * 10  # convert cm to mm
    else:
        df = pd.read_excel(fname) if fname.endswith('.xlsx') else pd.read_csv(fname)
    df = df.rename(columns={'height_cm': 'height'})
    length_column = [c for c in df.columns if c.startswith('length_L1-L5') or c.startswith('L1-L5_length')][0]
    print(f'{dataset}: {len(df)} subjects, length column: {length_column}')
    df = df.rename(columns={length_column: 'length_mm'})
    df['dataset'] = dataset
    return df[['dataset', 'subject', 'length_mm', 'sex', 'height']]


def datasets_in_order(df):
    """Datasets present in `df`, in the fixed order of DATASET_MARKERS."""
    return list(get_dataset_markers(df['dataset'].unique()))


def draw_height_marks(ax, heights, step=10):
    """
    Draw a short vertical line at the bottom of the plot where the height of the (height-sorted) subjects reaches each
    multiple of `step` cm, labelled with that height (e.g. '150 cm', '160 cm', ...). The line is placed just before the
    first subject with height >= that value; the label is drawn to its right so it never crosses the y-axis.
    :param ax: matplotlib axes
    :param heights: heights (cm) of the subjects in x-axis order (ascending), subject i at x = i + 1
    :param step: height step in cm (e.g. 10)
    """
    heights = np.asarray(heights, dtype=float)
    if len(heights) == 0:
        return
    transform = ax.get_xaxis_transform()  # x in data coordinates, y in axes coordinates
    first_mark = np.ceil(heights.min() / step) * step
    for mark in np.arange(first_mark, heights.max() + step / 2, step):
        idx = np.argmax(heights >= mark)  # first subject reaching this height (heights are sorted)
        if heights[idx] < mark:
            continue
        x_mark = idx + 1 - 0.5
        ax.plot([x_mark, x_mark], [0, 0.06], transform=transform, color='dimgray', linewidth=1, zorder=2,
                clip_on=False)
        ax.annotate(f'{mark:.0f} cm', xy=(x_mark, 0.02), xycoords=transform, xytext=(3, 0),
                    textcoords='offset points', ha='left', va='bottom', fontsize=FONT_SIZE - 3, color='dimgray')


def datasets_suffix(df):
    """Part of the output file names with the included datasets, e.g. 'balgrist_epfl_fudan'."""
    return '_'.join(dataset.lower() for dataset in datasets_in_order(df))


def generate_length_figure(df, dir_out, sort_by='height', height_step=10):
    """
    Length per subject: all subjects (females and males together) sorted by height or by the L1-L5 length (ascending).
    Sex is shown by color, the dataset by marker. When sorted by height, short vertical lines at the bottom mark where
    the height reaches each `height_step` cm.
    :param df: dataframe with 'dataset', 'subject', 'length_mm', 'sex' and 'height' columns
    :param dir_out: output folder
    :param sort_by: 'height' or 'length'
    :param height_step: step (cm) of the height marks drawn when sorted by height; 0 disables them
    """
    sort_cols = ['height', 'length_mm', 'subject'] if sort_by == 'height' else ['length_mm', 'height', 'subject']
    df = df.sort_values(sort_cols).reset_index(drop=True)
    x = np.arange(1, len(df) + 1)
    y = df['length_mm'].to_numpy() / 10  # convert mm to cm
    dataset_markers = get_dataset_markers(df['dataset'].unique())

    fig, ax = plt.subplots(figsize=SPINAL_REGIONAL_LENGTH_FIGSIZE)
    for dataset, marker in dataset_markers.items():
        for sex in SEXES:
            mask = ((df['sex'] == sex) & (df['dataset'] == dataset)).to_numpy()
            if mask.any():
                scatter_points(ax, x[mask], y[mask], color=SEX_COLOR[sex], marker=marker)

    # Height marks (only meaningful when the subjects are sorted by height)
    if sort_by == 'height' and height_step > 0:
        draw_height_marks(ax, df['height'].to_numpy(), height_step)

    sort_label = 'height' if sort_by == 'height' else 'L1–L5 length'
    ax.set_xticks([])   # subject IDs not shown
    ax.set_xlim(0.5, len(df) + 0.5)
    ax.set_xlabel(f'Subjects sorted by {sort_label}', fontsize=FONT_SIZE)
    ax.set_ylim(0, 8)
    ax.set_ylabel(YLABEL, fontsize=FONT_SIZE)
    ax.tick_params(axis='y', labelsize=FONT_SIZE - 2)
    ax.grid(axis='y', alpha=0.2)
    ax.set_axisbelow(True)
    ax.spines['right'].set_visible(False)
    ax.spines['top'].set_visible(False)
    add_legend_above(ax, legend_handles(df, dataset_markers))   # one row
    plt.tight_layout()

    sort_part = 'height' if sort_by == 'height' else 'lumbar_length'
    fname_figure = os.path.join(dir_out, f'figure_lumbar_length_L1-L5_{datasets_suffix(df)}_sorted_by_{sort_part}.png')
    fig.savefig(fname_figure, dpi=300)
    print(f'Figure saved to {fname_figure}')


def print_spearman(df, name):
    """Print the Spearman correlation between the height and the length for a subset of subjects."""
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    print(f'{name}: n = {len(df)}, Spearman rho = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')


def generate_correlation_figure(df, dir_out):
    """
    Length vs. height (all subjects pooled) with the shared correlation figure (visualisation_utils.plot_correlation):
    linear fit (visual guide) with its 95% confidence band and the Spearman correlation with its 95% CI. Per dataset
    and per sex, the Spearman correlation is only printed.
    """
    print_spearman(df, 'All subjects')
    for dataset in datasets_in_order(df):
        print_spearman(df[df['dataset'] == dataset], dataset)
    for sex in SEXES:
        print_spearman(df[df['sex'] == sex], SEX_LABEL[sex])

    df_plot = df.assign(length_cm=df['length_mm'] / 10)  # convert mm to cm
    fname_figure = os.path.join(dir_out, f'figure_correlation_lumbar_length_L1-L5_{datasets_suffix(df)}_height.png')
    plot_correlation(df_plot, 'height', 'length_cm', 'Height [cm]', YLABEL, fname_figure, integer_xticks=True,
                     panel_letter='B')


def print_summary(df):
    """
    Print a short overview of the L1-L5 length (mean ± SD [range]) to copy into an abstract.
    """
    def describe(values, unit='mm'):
        return f'{values.mean():.1f} ± {values.std():.1f} {unit} [{values.min():.1f}–{values.max():.1f}]'

    n_female, n_male = (df['sex'] == 'F').sum(), (df['sex'] == 'M').sum()
    female, male = df.loc[df['sex'] == 'F', 'length_mm'], df.loc[df['sex'] == 'M', 'length_mm']
    p_sex = stats.mannwhitneyu(female, male).pvalue
    rho, p = stats.spearmanr(df['height'], df['length_mm'])
    rho_lo, rho_hi = spearman_ci(rho, len(df))
    datasets = datasets_in_order(df)

    print('\n===== Summary: length top L1 – bottom L5 along the centerline (mean ± SD [range]) =====')
    print(f"All:      n = {len(df)} ({n_female} F / {n_male} M), {describe(df['length_mm'])}")
    for dataset in datasets:
        subset = df[df['dataset'] == dataset]
        print(f"{dataset + ':':<9} n = {len(subset)}, {describe(subset['length_mm'])}")
    print(f'Female:   n = {n_female}, {describe(female)}')
    print(f'Male:     n = {n_male}, {describe(male)}')
    print(f'Female vs. male: Mann-Whitney U p = {p_sex:.3f}')
    print(f"Height:   {describe(df['height'], unit='cm')}")
    print(f'Length vs. height: Spearman ρ = {rho:.2f} [95% CI {rho_lo:.2f}, {rho_hi:.2f}], p = {p:.3f}')
    print('=' * 88)

    # The same in a single sentence; the wording depends on the significance (p < 0.05)
    n_dataset = ', '.join(f"{dataset} n = {(df['dataset'] == dataset).sum()}" for dataset in datasets)
    sex_result = 'a significant' if p_sex < 0.05 else 'no significant'
    height_result = 'a significant' if p < 0.05 else 'no significant'
    print(f"\nIn {len(df)} participants ({n_female} F / {n_male} M; {n_dataset}), the spinal cord length from the top "
          f"of L1 to the bottom of L5 measured along the centerline was {df['length_mm'].mean():.1f} ± "
          f"{df['length_mm'].std():.1f} mm (range {df['length_mm'].min():.1f}–{df['length_mm'].max():.1f} mm), "
          f"with {sex_result} difference between females and males ({female.mean():.1f} ± {female.std():.1f} vs. "
          f"{male.mean():.1f} ± {male.std():.1f} mm, p = {p_sex:.3f}) and {height_result} correlation with body "
          f"height (Spearman ρ = {rho:.2f}, p = {p:.3f}).")


def main():
    parser = argparse.ArgumentParser(description='Combine the lumbar L1-L5 length of the Balgrist, EPFL, Fudan and '
                                                 'NeuroRestore datasets into a per-subject figure and a correlation with height.')
    parser.add_argument('-balgrist', default=BALGRIST_CSV,
                        help=f'CSV file with the Balgrist lengths. Default: {BALGRIST_CSV}')
    parser.add_argument('-epfl', default=EPFL_CSV,
                        help=f'CSV file with the EPFL lengths. Default: {EPFL_CSV}')
    parser.add_argument('-fudan', default=FUDAN_XLSX,
                        help=f'XLSX file with the Fudan lengths. Default: {FUDAN_XLSX}')
    parser.add_argument('-neurorestore', default=NEURORESTORE_TSV,
                        help=f"TSV file with the NeuroRestore lengths ('' to skip the dataset). "
                             f"Default: {NEURORESTORE_TSV}")
    parser.add_argument('-sort-by', choices=['height', 'length'], default='height',
                        help='Order of the subjects on the x-axis of the length figure: by height or by the L1-L5 '
                             'length (ascending). Default: height')
    parser.add_argument('-height-step', type=float, default=10,
                        help='When sorted by height, draw a short vertical line with a label (e.g. "150 cm", '
                             '"160 cm") where the height reaches each multiple of this step (cm); 0 disables them. '
                             'Default: 10')
    parser.add_argument('-o', default=OUTPUT_DIR,
                        help=f'Output folder for the CSV file and the figures. Default: {OUTPUT_DIR}')
    args = parser.parse_args()
    dir_out = os.path.abspath(os.path.expanduser(args.o))
    os.makedirs(dir_out, exist_ok=True)

    # Datasets to combine; a dataset whose file is set to '' is skipped
    files = {'Balgrist': args.balgrist, 'EPFL': args.epfl, 'Fudan': args.fudan, 'NeuroRestore': args.neurorestore}
    files = {dataset: fname for dataset, fname in files.items() if fname}
    # Check early that every dataset has a fixed marker in visualisation_utils.py
    get_dataset_markers(files)

    df = pd.concat([load_dataset(os.path.expanduser(fname), dataset) for dataset, fname in files.items()],
                   ignore_index=True)
    df['sex'] = df['sex'].str.upper()
    # Keep only subjects with the length, sex and height available
    n_all = len(df)
    df = df.dropna(subset=['length_mm', 'sex', 'height']).reset_index(drop=True)
    if len(df) < n_all:
        print(f'WARNING: {n_all - len(df)} subjects without length, sex or height excluded.')

    fname_csv = os.path.join(dir_out, f'lumbar_length_L1-L5_{datasets_suffix(df)}.csv')
    df.to_csv(fname_csv, index=False)
    print(f'CSV file saved in {fname_csv}.')

    generate_length_figure(df, dir_out, args.sort_by, args.height_step)
    generate_correlation_figure(df, dir_out)
    print_summary(df)
    plt.show()


if __name__ == '__main__':
    main()